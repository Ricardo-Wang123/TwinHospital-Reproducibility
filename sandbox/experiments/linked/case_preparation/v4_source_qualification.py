def load_frequency_context(case, private_data_root, *, source_package_root=None):
    src_id = case["provenance"]["source_case_id"]
    if not re.fullmatch(r"[A-Za-z0-9_-]+", src_id): raise ValueError("Unsafe source package name")
    bases = [Path(private_data_root)/n/"source_packages"/src_id for n in ("development_pilot50_v3", "development_pilot50_replacement_v1")]
    if source_package_root is not None:
        bases = [Path(source_package_root)/src_id]
    found = [p for p in bases if (p/"provenance.json").exists() and (p/"pharmacy_private.json").exists()]
    if len(found) != 1: raise ValueError("Expected exactly one preserved source package")
    folder=found[0]; provenance_path=folder/"provenance.json"; pharmacy_path=folder/"pharmacy_private.json"
    prov=json.loads(provenance_path.read_text()); pharmacy=json.loads(pharmacy_path.read_text())
    protected={str(p):file_hash(p) for p in (provenance_path,pharmacy_path)}
    index=defaultdict(list)
    for i,row in enumerate(pharmacy):
        index[tuple(str(row.get(k,"")) for k in ("subject_id","hadm_id","pharmacy_id"))].append((i,row))
    context={}; counter=Counter()
    for order in case["his_initial"]["historical_orders"]:
        raw=prov["source_rows"].get(order.get("source_ref"),{}).get("row")
        if not raw: counter["source_row_missing"]+=1; continue
        matches=index.get(tuple(str(raw.get(k,"")) for k in ("subject_id","hadm_id","pharmacy_id")),[])
        values={str(row.get("frequency") or "").strip() for _,row in matches}
        status="unique_agreement" if matches and len(values)==1 else "no_match" if not matches else "frequency_conflict"
        counter[status]+=1
        context[order["record_id"]]={"join_status":status, "frequency": next(iter(values)) if status=="unique_agreement" else None,
            "source_kind":"observed_source", "source_table":"pharmacy", "source_sidecar_sha256":protected[str(pharmacy_path)],
            "rows":[{"record_ref":"src_"+digest(row)[:24],"row_sha256":digest(row),"sidecar_row_index":i,
                     "frequency_raw":row.get("frequency"),"order_status_raw":row.get("status")}
                    for i,row in matches], "meaning":"historical order frequency/status only; not actual use"}
    return context, protected, dict(counter)


def product_form_gate(entry):
    r=entry["source_order"]["regimen_raw"]
    strength=str(r.get("prod_strength") or "").lower()
    mass=bool(re.search(r"\d\s*(?:mg|mcg|ug|g)\b",strength))
    if r.get("route")=="PO":
        if re.search(r"\b(?:tab(?:let)?|cap(?:sule)?|packet)\b",strength) and mass: return True, None
        if re.search(r"(?:mg|mcg|g)\s*/\s*\d*\.?\d*\s*ml",strength): return True, None
        return False,"oral_form_or_mass_per_unit_not_explicit"
    if r.get("route") in {"IH","INH","NEB"}:
        # A 12g canister is not an active-ingredient strength per actuation.
        active_mass=bool(re.search(r"\d\s*(?:mg|mcg|ug)\b",strength))
        form=bool(re.search(r"diskus|inhal|capsule|vial|neb|respule",strength))
        if active_mass and form: return True,None
        return False,"inhaled_active_strength_or_device_not_explicit"
    return False,"route_not_supported"


def qualify(case, context):
    entries,exclusions=candidate_plan(case,context); candidates=[]
    for entry in entries:
        name=(entry["source_order"].get("drug_name_raw") or "").casefold()
        matches=[term for term in CORE_TERMS[case["group"]] if term in name]
        if not matches: continue
        form_ok,form_reason=product_form_gate(entry)
        candidates.append({"source_order_ref":entry["source_order"]["record_id"],"matched_family_terms":matches,
            "regimen_reasons":entry["reasons"],"form_status":"parseable_pattern" if form_ok else form_reason,
            "source_material_gate":not entry["reasons"] and form_ok,
            "indication_status":"not_verified_for_this_individual", "appropriateness_status":"independent_review_pending"})
    return {"source_material_gate":any(x["source_material_gate"] for x in candidates),
        "core_candidate_count":len(candidates),"core_parseable_count":sum(x["source_material_gate"] for x in candidates),
        "core_candidates":candidates,"all_scheduled_candidate_count":sum(not x["reasons"] for x in entries),
        "candidate_window_count":len(entries),"excluded_source_order_counts":exclusions,
        "clinical_qualification":"pending","normal_control_status":"not_assigned"}


def generate(manifest_path, private_data_root, output):
    manifest_path,output=Path(manifest_path).resolve(),Path(output).resolve()
    if output.exists(): raise FileExistsError("Preserve previous source qualification and previews")
    m=json.loads(manifest_path.read_text()); protected={str(manifest_path):file_hash(manifest_path)}
    tmp=Path(tempfile.mkdtemp(prefix="."+output.name+".",dir=output.parent));tmp.chmod(0o700)
    try:
        write(tmp/"source_policy_frozen_before_cases.json",{"policy":QUALIFICATION_POLICY,
            "qualification_code_sha256":file_hash(__file__),"episode_code_sha256":file_hash(Path(__file__).with_name("current_episode_v4.py"))})
        rows=[];contexts={};sources={};groupstats=defaultdict(Counter)
        for i,e in enumerate(m["cases"],1):
            if file_hash(e["path"])!=e["sha256"]: raise ValueError("Source frozen case changed")
            protected[e["path"]]=e["sha256"];c=json.loads(Path(e["path"]).read_text())
            context, p, counts=load_frequency_context(c,private_data_root);protected.update(p)
            qualification=qualify(c,context);contexts[e["case_id"]]=context;sources[e["case_id"]]=c
            rows.append({"candidate_index":f"C{i:03d}","case_id":e["case_id"],"source_entry":e,"frequency_join_counts":counts,**qualification})
            groupstats[e["group"]].update(cases=1,source_material_gate=int(qualification["source_material_gate"]),
                core_family_seen=int(qualification["core_candidate_count"]>0),core_parseable_items=qualification["core_parseable_count"])
        first=m["cases"][:3]
        if [e["group"] for e in first] != ["type2_diabetes","heart_failure","copd"]: raise ValueError("Unexpected frozen source order")
        next_t2=next((r for r in rows if r["source_entry"]["group"]=="type2_diabetes" and r["case_id"]!=first[0]["case_id"] and r["source_material_gate"]),None)
        selected=[next_t2["source_entry"] if next_t2 else first[0],first[1],first[2]]
        source_rows={r["case_id"]:r for r in rows}
        previews=[];audits=[];products=Counter()
        for e in selected:
            c,check=build_episode(sources[e["case_id"]],contexts[e["case_id"]])
            c["evaluation"]["source_material_qualification"]=deepcopy(source_rows[e["case_id"]])
            c["provenance"]["source_qualification_policy"]=deepcopy(QUALIFICATION_POLICY)
            c["provenance"]["source_frequency_annotations"]=contexts[e["case_id"]]
            relative=Path("cases")/(c["case_id"]+".json");write(tmp/relative,c)
            p=deepcopy(e);p.update(case_id=c["case_id"],path=str(output/relative),sha256=file_hash(tmp/relative),formal_eligible=False,
                parent_source_entry=deepcopy(e),
                clinical_suitability="pending_independent_input_review",clinical_reference_status="pending_independent_review",
                prescribing_required=False,constructed_view_complete=True)
            previews.append(p);audits.append({"case_id":c["case_id"],"source_case_id":e["case_id"],"source_material_gate":source_rows[e["case_id"]]["source_material_gate"],**check})
            for item in c["his_initial"]["current_use_record"]["items"]:
                products[(item["name"],item["strength"],item["route"],item["current_use_status"])]+=1
        if any(file_hash(p)!=h for p,h in protected.items()):raise RuntimeError("Source mutation during preparation")
        manifest={"version":VERSION,"cases":previews,"case_count":len(previews),"formal_eligible":False,"new_run_required":True,
            "purpose":"input review before paid execution; clinical reference pending", "source_manifest":str(manifest_path),
            "source_selection_policy":deepcopy(QUALIFICATION_POLICY), "source_manifest_sha256":file_hash(manifest_path)}
        write(tmp/"manifest.json",manifest)
        write(tmp/"qualification50_private.json",{"policy":QUALIFICATION_POLICY,"cases":rows})
        write(tmp/"source_hash_audit_private.json",{"protected_source_files":protected,"all_unchanged":True})
        write(tmp/"preview_audit_private.json",{"cases":audits})
        summary={"version":VERSION,"source_cases_screened":len(rows),"source_core_pattern_gate_by_group":dict(groupstats),
            "replacement_t2_selected_in_frozen_order":next_t2 is not None,"generated_cases":len(previews),
            "clinical_approved_cases":0,"clinical_gold_labels":0,"model_outputs_read":False,"model_calls":0,
            "all_source_hashes_unchanged":True,"preview_by_group":[{"group":e["group"],**{k:a[k] for k in ("source_material_gate","candidate_count","scheduled_plan_count","unresolved_candidate_count","maximum_projected_current_page_bytes")}} for e,a in zip(previews,audits)]}
        write(tmp/"summary.json",summary)
        write(tmp/"candidate_products_aggregate.json",{"products":[{"name_raw":k[0],"strength_raw":k[1],"route_raw":k[2],"current_status":k[3],"case_count":v} for k,v in sorted(products.items())]})
        write(tmp/"input_freeze.json",{"files":[{"path":str(output/p.relative_to(tmp)),"sha256":file_hash(p)} for p in sorted(tmp.rglob("*")) if p.is_file()]})
        tmp.rename(output);return summary
    except BaseException:
        shutil.rmtree(tmp);raise


