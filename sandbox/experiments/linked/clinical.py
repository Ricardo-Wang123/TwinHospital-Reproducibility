    def event(self, kind, **fields):
        row = {"sequence": len(self.events) + 1, "occurred_at": _utc(),
               **self.context, "event": kind, **deepcopy(fields),
               "clock_id":self.clock_id,"elapsed_seconds":time.monotonic()-self.clock_origin}
        self.events.append(row)
        self.journal("events.jsonl", row)

    def journal(self, filename, value):
        if self.directory is None:
            return
        descriptor = os.open(self.directory / filename, os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
        with os.fdopen(descriptor, "a", encoding="utf-8") as stream:
            stream.write(json.dumps(value, ensure_ascii=False, allow_nan=False) + "\n")
            stream.flush()
            os.fsync(stream.fileno())

    def activity(self, role, kind):
        seconds = self.runner.timing[kind]
        self.activities.append({"activity_id": f"{self.prefix}:activity:{len(self.activities)+1}",
                                **self.context, "role": role, "activity_type": kind,
                                "active_seconds": seconds, "timing_source": self.runner.timing_source})

    def respond(self, role, observation, *, phase, family=None):
        contract = contract_for(role, observation.get("action"))
        base = {**deepcopy(observation), "required_response": {"format": "json_object",
                    "shape_description": "Required response: " + contract["required_response"]},
                "allowed_response_actions": contract.get("response_actions", []),
                "allowed_decisions": contract.get("allowed_decisions", []),
                "response_contract_version": RESPONSE_CONTRACT_POLICY["version"]}
        if role != 'patient':
            # This contract contains no case values and reveals no hidden facts.
            # Keep it next to each request, including review and follow-up, so
            # source provenance is not mistaken for an unperformed virtual test.
            base['simulation_scope'] = deepcopy(SIMULATION_SCOPE_POLICY)
        original_hash = digest(base)
        current = base
        for correction in range(RESPONSE_CONTRACT_POLICY["max_schema_corrections"] + 1):
            try:
                response = self._respond_once(role, current, phase=phase, family=family,
                                              correction=correction, original_input_hash=original_hash)
            except (json.JSONDecodeError, DuplicateJSONKeyError) as exc:
                # Never extract a convenient JSON fragment or reinterpret a
                # malformed clinical decision. Ask the same role once to return
                # its intended response in the contract, preserving the failure.
                # A duplicate-key object has no selected clinical decision.
                # It receives the same single format retry, never last-key-wins.
                # Truncation, nonfinite values, transport and budget exceptions
                # remain ineligible for this correction.
                metadata = deepcopy(getattr(exc, 'parse_metadata', None)) or {}
                permitted = (correction < RESPONSE_CONTRACT_POLICY['max_schema_corrections']
                    and metadata.get('finish_reason') == 'stop'
                    and not metadata.get('normalization_performed')
                    and len(exc.doc.encode('utf-8')) <= RESPONSE_CONTRACT_POLICY['max_invalid_response_bytes'])
                self.event('role_response_json_invalid', role=role, phase=phase,
                    response_text_hash=digest(exc.doc), parse_metadata=metadata,
                    correction_attempt=correction, correction_scheduled=permitted,
                    original_clinical_input_hash=original_hash)
                if not permitted:
                    raise
                current = {**deepcopy(base), 'schema_correction': {
                    'attempt':correction+1, 'max_attempts':RESPONSE_CONTRACT_POLICY['max_schema_corrections'],
                    'previous_invalid_response_hash':digest(exc.doc),
                    'previous_response_storage':'private_provider_evidence_not_reinjected_as_opaque_input',
                    'contract_errors':['The completed response was not exactly one unambiguous valid JSON object: '+exc.msg],
                    'original_clinical_input_hash':original_hash,
                    'instruction':'Your previous response failed JSON format validation and is retained in the private run evidence. Answer the unchanged clinical input in exactly one JSON object using the required response contract, with each object key appearing once and no prose outside JSON. Preserve the evidence and uncertainty; a defer/rejection/no-prescription decision remains permissible. Do not invent clinical facts, seek a preferred clinical outcome, or claim a business action. This is the sole format retry; no fragment or duplicate field value from the malformed response was selected as a clinical decision.'}}
                continue
            canonical, moves = normalize_structure(role, observation.get('action'), response)
            if moves:
                proof = {'policy': RESPONSE_CONTRACT_POLICY['lossless_structure_normalization'],
                    'role': role, 'phase': phase, 'call_sequence': len(self.calls),
                    'original_response': deepcopy(response), 'original_response_hash': digest(response),
                    'canonical_response': deepcopy(canonical), 'canonical_response_hash': digest(canonical),
                    'field_moves': moves, 'clinical_values_changed': False, 'extra_model_call': False}
                self.result['artifacts'].setdefault('response_structure_normalizations', []).append(proof)
                self.journal('response_structure_normalizations.jsonl', proof)
                self.event('role_response_structure_normalized', role=role, phase=phase,
                    call_sequence=len(self.calls), policy=proof['policy'], field_moves=moves,
                    original_response_hash=proof['original_response_hash'],
                    canonical_response_hash=proof['canonical_response_hash'], clinical_values_changed=False)
                response = canonical
            errors = _response_shape_errors(role, observation, response)
            if not errors:
                return response
            permitted = correction < RESPONSE_CONTRACT_POLICY["max_schema_corrections"] and schema_correction_allowed(response)
            self.event("role_response_schema_invalid", role=role, phase=phase,
                response_hash=digest(response), contract_errors=errors,
                correction_attempt=correction, correction_scheduled=permitted,
                original_clinical_input_hash=original_hash)
            if not permitted:
                if role == "senior_pharmacist":
                    self.result["artifacts"]["unresolved_prescription_adjudication"] = {
                        "status": "invalid_response_contract", "response": deepcopy(response),
                        "prescription_hash": digest(observation.get("prescription")),
                        "clinical_appropriateness": "not_assessed_outside_programmatic_scope"}
                raise WorkflowFailure("role response contract not satisfied: " + "; ".join(errors))
            current = {**deepcopy(base), "schema_correction": {
                "attempt": correction+1, "max_attempts": RESPONSE_CONTRACT_POLICY["max_schema_corrections"],
                "previous_invalid_response": deepcopy(response), "contract_errors": errors,
                "original_clinical_input_hash": original_hash,
                "instruction": "Correct only the role/action/JSON structure using the unchanged clinical inputs. Preserve facts, decisions and uncertainty. Do not invent clinical content, infer missing facts, or claim an application action. Return the requested artifact; an old draft is not automatically accepted."}}
        raise AssertionError("unreachable schema correction")

    def _respond_once(self, role, observation, *, phase, family=None, correction=0, original_input_hash=None):
        assert_visible(observation)
        key = (phase, role, family)
        if key not in self.sessions:
            scope = f"{self.context['run_id']}:{self.case['case_id']}:{self.context['config_id']}:{phase}"
            self.sessions[key] = self.runner.factory.session(scope, role, family)
        session = self.sessions[key]
        visible = {**deepcopy(observation), "data_kind": self.case["data_kind"]}
        call = {"sequence": len(self.calls)+1, "role": role, "phase": phase,
                "model_family": family, "observation_hash": digest(visible), "observation": visible,
                "schema_correction_attempt": correction, "original_clinical_input_hash": original_input_hash,
                "started_at": _utc()}
        start = time.monotonic()
        try:
            response = session.respond(visible)
            if not isinstance(response, dict):
                raise WorkflowFailure("role returned a non-object response")
            assert_visible(response)
            errors = _response_shape_errors(role, observation, response)
            call.update(status="invalid_schema" if errors else "completed", response=deepcopy(response),
                        response_hash=digest(response), response_schema_errors=errors)
            return deepcopy(response)
        except KeyboardInterrupt:
            call.update(status="interrupted", error_type="KeyboardInterrupt")
            raise
        except Exception as exc:
            call.update(status="failed", error_type=type(exc).__name__, error=str(exc)[:500])
            raise
        finally:
            call.update(wall_seconds=time.monotonic()-start,
                        usage=deepcopy(getattr(session, "last_usage", None)),
                        model_name=getattr(session, "model_name", None),
                        memory_policy=getattr(session, "memory_policy", None),
                        response_parse=deepcopy(getattr(session, "last_parse_metadata", None)),
                        request_id=getattr(session, "last_request_id", None))
            self.calls.append(call)
            self.journal("calls.jsonl", call)
            self.event("role_call", role=role, phase=phase, model_family=family,
                       call_sequence=call["sequence"], status=call["status"],
                       observation_hash=call["observation_hash"], response_hash=call.get("response_hash"))

    def perform(self, operation, payload, role="doctor", *, write=True):
        self.request_sequence+=1
        request_id=self.prefix+':business:'+str(self.request_sequence)
        context = {**self.context, "role": role, "actor_id": role + "-1",
                   "action_request_id":request_id,
                   "idempotency_key": self.prefix + ":" + operation + ":" + digest(payload)[:20]}
        started = time.monotonic()
        self.event('business_request_intent',request_id=request_id,operation=operation,
                   scope=deepcopy(context),payload_hash=digest(payload))
        try:
            response = self.runner.backend.execute(operation, deepcopy(payload), context)
        except Exception as exc:
            self.event('business_request_outcome',request_id=request_id,operation=operation,
                       status='unresolved_exception',error_type=type(exc).__name__,native_effect=None)
            # A raised request can have an uncertain native effect. Record the
            # attempted operation, but do not assert that it was safely undone.
            self.event("business_operation", operation=operation, role=role, payload_hash=digest(payload),request_id=request_id,
                response={"status": "failed_exception", "error_type": type(exc).__name__,
                    "readback_verified": False, "native_effect": None,
                    "protection_source": "runtime_observed_exception_native_effect_unknown"},
                wall_seconds=time.monotonic()-started)
            raise
        if not isinstance(response, dict):
            self.event('business_request_outcome',request_id=request_id,operation=operation,
                       status='unresolved_invalid_response',native_effect=None)
            self.event("business_operation", operation=operation, role=role, payload_hash=digest(payload),request_id=request_id,
                response={"status": "invalid_response", "readback_verified": False, "native_effect": None},
                wall_seconds=time.monotonic()-started)
            raise WorkflowFailure("backend returned a non-object response")
        self.event('business_request_outcome',request_id=request_id,operation=operation,
                   status='response_observed',response_hash=digest(response),
                   readback_verified=response.get('readback_verified'),native_effect=response.get('native_effect'))
        boundary={}
        if operation=='queue.enter' and response.get('readback_verified') and response.get('status') in {'executed','replayed','ok'}:
            boundary={'clock_boundary':'queue_entry_persisted'}
        self.event("business_operation", operation=operation, role=role, payload_hash=digest(payload),request_id=request_id,
                   response=deepcopy(response), wall_seconds=time.monotonic()-started,**boundary)
        if response.get("status") not in {"executed", "replayed", "ok"}:
            raise WorkflowFailure(f"{operation} rejected: {response.get('reason', 'unknown')}")
        if not response.get("readback_verified"):
            raise WorkflowFailure(operation + " has no verified persistence/read-back")
        data = response.get("data")
        if not isinstance(data, dict):
            raise WorkflowFailure(operation + " returned no structured data")
        return data

    def register(self):
        patient = self.case["patient_initial"]
        data = self.perform("registration.create", {"patient_key": self.case["patient_key"],
                            "demographics": deepcopy(patient.get("demographics", {}))}, "administrator")
        if not data.get("patient_id") or not data.get("encounter_id"):
            raise WorkflowFailure("registration did not return patient and encounter IDs")
        self.context.update(patient_id=data["patient_id"], encounter_id=data["encounter_id"])
        self.result.update(self.context)
        queued = self.perform("queue.enter", {"encounter_id": self.context["encounter_id"]}, "administrator")
        if str(queued.get("encounter_id")) != str(self.context["encounter_id"]):
            raise WorkflowFailure("queue read-back does not match registered encounter")
        self.perform("history.import", {"history": self.case["his_initial"]}, "administrator")
        initial = self.perform("history.index", {}, "doctor", write=False).get("history")
        if not isinstance(initial, dict) or initial.get("view_type") != "bounded_history_directory":
            raise WorkflowFailure("bounded hospital history directory missing")
        if json_bytes(initial) > INITIAL_BYTE_LIMIT:
            raise WorkflowFailure("hospital history directory exceeds its byte limit")
        self.history = {"initial_view": initial, "queried_pages": [], "last_query_feedback": None,
                        "visible_history_byte_limit": HISTORY_CONTEXT_BYTE_LIMIT,
                        "unshown_is_not_absent": True}
        self.result["artifacts"]["visible_history"] = deepcopy(self.history)
        self.diagnosis_catalogue = self.perform("diagnosis.catalogue", {}, "doctor", write=False).get("items", [])
        if not isinstance(self.diagnosis_catalogue, list):
            raise WorkflowFailure("diagnosis catalogue must be a list")
        self.event("encounter_registered", history_hash=digest(self.history))

    def restore_frozen_history(self, history):
        if (not isinstance(history, dict) or json_bytes(history) > HISTORY_CONTEXT_BYTE_LIMIT or
                set(history) - {"initial_view", "queried_pages", "last_query_feedback", "visible_history_byte_limit", "unshown_is_not_absent"} or
                digest(history.get("initial_view")) != digest(self.history["initial_view"])):
            raise WorkflowFailure("frozen bounded history does not match this case directory")
        self.history = deepcopy(history)
        self.result["artifacts"]["visible_history"] = deepcopy(self.history)

    def history_queries_remaining(self, phase):
        return self.runner.limits["history_queries_per_phase"] - self.history_query_counts.get(phase, 0)

    def read_history(self, action, phase, *, actor_role="doctor"):
        reconciliation_phase = (phase.startswith('in_hospital_reconciliation_') and
            phase[len('in_hospital_reconciliation_'):].isdigit() and actor_role == 'pharmacist')
        if phase not in PHYSICIAN_DIALOGUE_PHASES and not reconciliation_phase:
            raise WorkflowFailure("history lookup is unavailable in this role phase")
        if self.history_queries_remaining(phase) <= 0:
            raise WorkflowFailure("physician history lookup limit exhausted")
        request = {k: deepcopy(action[k]) for k in ("section", "encounter_key", "term", "offset", "limit") if k in action}
        request.setdefault("offset", 0)
        request.setdefault("limit", 5)
        validation_errors = []
        if request.get("section") not in self.history["initial_view"].get("sections", {}):
            validation_errors.append("unknown clinical chart section; choose a section from initial_view.sections")
        if (type(request["offset"]) is not int or request["offset"] < 0 or
                type(request["limit"]) is not int or not 1 <= request["limit"] <= MAX_PAGE_RECORDS):
            validation_errors.append("offset must be an integer >=0 and limit must be an integer in 1..20")
        if request.get("term") is not None and (not isinstance(request["term"], str) or len(request["term"]) > 128):
            validation_errors.append("term must be a string of at most 128 characters")
        if request.get('encounter_key') is not None and not isinstance(request['encounter_key'],str):
            validation_errors.append('encounter_key must be a returned encounter_ref string')
        self.history_query_counts[phase] = self.history_query_counts.get(phase, 0) + 1
        if actor_role not in {'doctor', 'pharmacist'}:
            raise WorkflowFailure('History lookup actor is not authorized')
        self.activity(actor_role, "history_lookup")
        self.event("history_query_requested", phase=phase, section=request["section"],
                   request=request, query_hash=digest(request), lookup_number=self.history_query_counts[phase])
        if validation_errors:
            # A failed tool request consumes the existing lookup budget and is
            # visible to its caller. No clamping, substitute search or HIS read.
            self.history['last_query_feedback'] = {'status':'invalid_request',
                'request':deepcopy(request), 'validation_errors':validation_errors,
                'remaining_queries_this_phase':self.history_queries_remaining(phase),
                'accepted_into_context':False,
                'instruction':'No records were read. Correct the request within the remaining query budget; this is not evidence of absent clinical information.'}
            self.result['artifacts']['visible_history'] = deepcopy(self.history)
            self.event('history_lookup', phase=phase, section=request['section'],
                query_hash=digest(request), lookup_number=self.history_query_counts[phase],
                returned_refs=[], returned_count=0, accepted_into_context=False,
                result_status='invalid_request', validation_errors=validation_errors,
                native_read_attempted=False, wall_seconds=0)
            return
        if (request["section"] == "current_observations" and phase != "consultation"
                and not (reconciliation_phase and self.current_measurement_panel is not None)):
            self.history["last_query_feedback"] = {"section": request["section"],
                "status": "not_available_before_physician_consultation",
                "remaining_queries_this_phase": self.history_queries_remaining(phase),
                "instruction": "Current measurements are released at consultation entry; do not infer their values now."}
            self.event("history_lookup", phase=phase, section=request["section"], query_hash=digest(request),
                lookup_number=self.history_query_counts[phase], returned_refs=[], returned_count=0,
                accepted_into_context=False, result_status="not_available_before_physician_consultation", wall_seconds=0)
            return
        start = time.monotonic()
        try:
            page = self.perform("history.query", request, actor_role, write=False).get("page")
        except Exception as exc:
            self.event("history_lookup", phase=phase, section=request["section"], query_hash=digest(request),
                lookup_number=self.history_query_counts[phase], returned_refs=[], returned_count=0,
                accepted_into_context=False, result_status="failed_read", error_type=type(exc).__name__,
                wall_seconds=time.monotonic()-start)
            raise
        elapsed = time.monotonic() - start
        if (not isinstance(page, dict) or not isinstance(page.get("records"), list) or
                page.get("section") != request["section"] or json_bytes(page) > PAGE_BYTE_LIMIT):
            raise WorkflowFailure("invalid or oversized history query response")
        raw_page = deepcopy(page)
        if request["section"] == "current_observations":
            page = deepcopy(page)
            before_count = len(page["records"])
            page["records"] = [row for row in page["records"]
                               if row.get("record", {}).get("available_at") == "physician_consultation"]
            page["returned_count"] = len(page["records"])
            page["withheld_unavailable_records"] = before_count-len(page["records"])
        refs = [row.get("record_ref") for row in page["records"]]
        if any(not isinstance(ref, str) or not ref for ref in refs):
            raise WorkflowFailure("history page lacks stable record references")
        try:
            projected = project_history_page(page)
        except ProjectionBudgetExceeded as exc:
            # A legitimate source page may gain framing overhead even without
            # compressible shared fields. Reject only this view, not the visit.
            self.journal("history_query_raw.jsonl", {"phase": phase, "request": request,
                "query_number": self.history_query_counts[phase], "raw_page": raw_page,
                "raw_page_hash": digest(raw_page), "released_page_hash": digest(page),
                "projection_version": PROJECTION_POLICY["version"],
                "projection_status": "requires_narrower_query_for_projected_page_budget",
                "projected_page_bytes": exc.projected_bytes})
            self.history["last_query_feedback"] = None
            retained_bytes = json_bytes(self.history)
            self.history["last_query_feedback"] = {"section": request["section"],
                "status": "requires_narrower_query_for_projected_page_budget",
                "returned_count": len(refs), "matching_count": page.get("matching_count"),
                "next_offset": page.get("next_offset"), "accepted_into_context": False,
                "remaining_queries_this_phase": self.history_queries_remaining(phase),
                "retained_context_bytes": retained_bytes,
                "remaining_visible_bytes": max(0, HISTORY_CONTEXT_BYTE_LIMIT-1024-retained_bytes),
                "raw_page_bytes": json_bytes(raw_page), "projected_page_bytes": exc.projected_bytes,
                "instruction": "This page exceeds the view page budget; a smaller query may help, but no returned clinical value is visible from this read. Unknown is not absent."}
            self.event("history_lookup", phase=phase, section=request["section"], request=request,
                query_hash=digest(request), lookup_number=self.history_query_counts[phase], returned_refs=refs,
                returned_count=len(refs), accepted_into_context=False,
                result_status="requires_narrower_query_for_projected_page_budget", wall_seconds=elapsed,
                raw_page_bytes=json_bytes(raw_page), projected_page_bytes=exc.projected_bytes,
                raw_page_hash=digest(raw_page), projection_version=PROJECTION_POLICY["version"],
                retained_context_bytes=json_bytes(self.history))
            self.result["artifacts"]["visible_history"] = deepcopy(self.history)
            return
        if not verify_projection(page, projected):
            raise WorkflowFailure("history projection changed clinical evidence")
        dedup = deduplicate_projected_page(projected, self.history["queried_pages"])
        if not verify_projection(page, dedup["page"], self.history["queried_pages"]):
            raise WorkflowFailure("history deduplication changed clinical evidence")
        self.journal("history_query_raw.jsonl", {"phase": phase, "request": request,
            "query_number": self.history_query_counts[phase], "raw_page": raw_page,
            "raw_page_hash": digest(raw_page), "released_page_hash": digest(page),
            "projected_page_hash": digest(projected), "projection_version": PROJECTION_POLICY["version"],
            "projected_source_page_hash": projected["source_page_sha256"],
            "withheld_unavailable_record_count": page.get("withheld_unavailable_records", 0)})
        entry = {"page": dedup["page"], "phase": phase,
                 "queried_after_sequence": self.transcript[-1]["sequence"] if self.transcript else 0}
        trial = deepcopy(self.history)
        trial["last_query_feedback"] = None
        repeated = dedup["all_records_already_visible"] or any(
            digest(old["page"]) == digest(dedup["page"]) for old in trial["queried_pages"])
        if not repeated:
            trial["queried_pages"].append(entry)
        accepted = json_bytes(trial) <= HISTORY_CONTEXT_BYTE_LIMIT - 1024
        status = ("already_visible" if repeated else "visible") if accepted else "requires_narrower_query_for_visible_context_budget"
        if accepted:
            self.history = trial
        retained = deepcopy(self.history)
        retained["last_query_feedback"] = None
        retained_bytes = json_bytes(retained)
        feedback = {"section": request["section"], "status": status,
            "returned_count": len(refs), "matching_count": page.get("matching_count"),
            "next_offset": page.get("next_offset"), "remaining_queries_this_phase": self.history_queries_remaining(phase),
            "retained_context_bytes": retained_bytes, "remaining_visible_bytes": max(0, HISTORY_CONTEXT_BYTE_LIMIT-1024-retained_bytes),
            "raw_page_bytes": json_bytes(raw_page), "projected_page_bytes": json_bytes(projected),
            "accepted_into_context": accepted,
            "already_visible_record_count": len(dedup["already_visible_record_refs"]),
            "instruction": "Unknown/unshown is not absent. Existing identical records are shared; pagination still applies. A smaller query is not guaranteed to fit the remaining bytes."}
        self.history["last_query_feedback"] = feedback
        if json_bytes(feedback) > 1024 or json_bytes(self.history) > HISTORY_CONTEXT_BYTE_LIMIT:
            raise WorkflowFailure("history feedback exceeded its reserved visible budget")
        self.event("history_lookup", phase=phase, section=request["section"], request=request,
            query_hash=digest(request), lookup_number=self.history_query_counts[phase], returned_refs=refs,
            returned_count=len(refs), accepted_into_context=accepted, result_status=status,
            wall_seconds=elapsed, retained_context_bytes=json_bytes(self.history),
            remaining_visible_bytes=feedback["remaining_visible_bytes"],
            raw_page_bytes=json_bytes(raw_page), projected_page_bytes=json_bytes(projected),
            raw_page_hash=digest(raw_page), projected_page_hash=digest(projected),
            projection_version=PROJECTION_POLICY["version"],
            already_visible_record_refs=dedup["already_visible_record_refs"],
            new_record_refs=dedup["new_record_refs"] if accepted else [],
            next_offset=page.get("next_offset"), matching_count=page.get("matching_count"))
        self.result["artifacts"]["visible_history"] = deepcopy(self.history)

    def say(self, role, text, *, phase):
        if not isinstance(text, str) or not text.strip():
            raise WorkflowFailure("dialogue text is empty")
        sequence = max((row['sequence'] for row in self.transcript), default=0) + 1
        segment = {"sequence": sequence, "speaker_role": role, "text": text,
                   "phase": phase, "available_at_ms": (sequence-1)*1000}
        # available_at_ms is ordering metadata, not measured or modeled human speaking time.
        self.transcript.append(segment)
        return segment

    def ask_patient(self, role, question, phase):
        self.say(role, question, phase=phase)
        answer = self.respond("patient", {"action": "answer", "question": question,
                "patient_memory": self.case["patient_initial"],
                "conversation": deepcopy(self.transcript)}, phase=phase)
        if answer.get("action") != "answer":
            raise WorkflowFailure("patient response must use action=answer")
        self.say("patient", answer.get("text"), phase=phase)
        memory_ids = {f["fact_id"] for f in self.case["patient_initial"]["patient_facts"]}
        expressed = answer.get("expressed_fact_ids", [])
        if not isinstance(expressed, list):
            raise WorkflowFailure("expressed_fact_ids must be a list")
        unknown = [x for x in expressed if x not in memory_ids]
        if unknown:
            # A patient-model hallucination is observed, not silently corrected or deleted.
            self.event("patient_fact_pointer_error", unknown_fact_ids=unknown)

    def inquiry(self, role, action, limit, *, phase, family=None, prior_summary=None):
        turn = 0
        while turn <= limit:
            # A physician receives the persisted handoff, not the collector's hidden
            # original conversation. Missing handoff information must be re-elicited.
            conversation = self.physician_transcript() if role == "doctor" else deepcopy(self.transcript)
            observation = {"action": action, "conversation": conversation,
                           "prior_summary": deepcopy(prior_summary),
                           "demographics": deepcopy(self.case["patient_initial"].get("demographics", {})),
                           "remaining_interactions": limit-turn}
            if role == "doctor":
                observation["hospital_history"] = deepcopy(self.history)
                observation["remaining_history_queries"] = self.history_queries_remaining(phase)
            response = self.respond(role, observation, phase=phase, family=family)
            if role == "doctor" and response.get("action") == "read_history":
                self.read_history(response, phase)
                continue
            if response.get("action") == "summary":
                content = response.get("content")
                if not isinstance(content, dict) or not isinstance(content.get("text"), str):
                    raise WorkflowFailure("summary requires content.text")
                if role == "nurse":
                    self.activity(role, "summary_documentation")
                return content
            if response.get("action") != "ask" or turn >= limit:
                raise WorkflowFailure("inquiry did not finish within the declared interaction limit")
            if role == "doctor":
                purpose = response.get("question_purpose", "handoff_verification")
                if purpose not in {"handoff_verification", "handoff_supplementation", "handoff_correction"}:
                    raise WorkflowFailure("diagnostic inquiry must be outside the handoff-effort phase")
                self.activity(role, purpose)
            elif role == "nurse":
                self.activity(role, "information_collection")
            self.ask_patient(role, response.get("question"), phase)
            turn += 1
        raise AssertionError("unreachable inquiry")

    def preconsult(self, condition):
        flow, family = condition.workflow, condition.model_family
        role = "nurse" if flow == "nurse_only" else "preconsult_ai"
        first = self.inquiry(role, "collect", self.runner.limits["preconsult_turns"],
                             phase="preconsult_collection", family=family)
        self.result["artifacts"]["initial_summary"] = deepcopy(first)
        if flow == "ai_nurse_review":
            self.activity("nurse", "summary_review")
            first = self.inquiry("nurse", "review_summary", self.runner.limits["nurse_review_turns"],
                                 phase="nurse_summary_review", prior_summary=first)
        self.handoff = deepcopy(first)
        self.result["artifacts"]["final_handoff"] = deepcopy(first)
        artifact_id = self.prefix + ":handoff"
        self.perform("handoff.save", {"artifact_id": artifact_id, "content": first, "version": 1},
                     "nurse" if flow != "ai_only" else "preconsult_ai")
        saved = self.perform("handoff.read", {"artifact_id": artifact_id}, "doctor", write=False).get("content")
        if digest(saved) != digest(first):
            raise WorkflowFailure("handoff read-back does not match persisted summary")
        self.handoff = saved
        self.activity("doctor", "handoff_verification")
        verified = self.inquiry("doctor", "verify_handoff", self.runner.limits["handoff_verification_turns"],
                                phase="doctor_handoff_verification", prior_summary=saved)
        # Clinical quality is scored on final_handoff before downstream physician repair.
        self.result["artifacts"]["physician_verified_handoff"] = deepcopy(verified)
        self.handoff = verified
        self.event("preconsult_completed", final_handoff_hash=digest(first),
                   physician_verified_hash=digest(verified), condition=condition.to_dict())

    def clinical_context(self):
        return {"hospital_history": deepcopy(self.history), "handoff": deepcopy(self.handoff),
                "current_encounter_measurements": deepcopy(self.current_measurement_panel),
                "consultation": deepcopy(self.consultation_record), "conversation": self.physician_transcript()}

    def prepare_rule_context(self, context):
        prepare = getattr(self.runner.pprs, "prepare_context", None)
        if prepare is None:
            return deepcopy(context)
        prepared = prepare(context)
        shared, index, audit = prepared["shared_context"], prepared["evidence_index"], prepared["audit"]
        assert_visible(shared)
        indexes = self.result["artifacts"].setdefault("rule_evidence_indexes", {})
        identity = index["index_hash"]
        if identity not in indexes:
            indexes[identity] = deepcopy(index)
            self.journal("rule_evidence.jsonl", {"evidence_index": index, "audit": audit})
            self.event("rule_context_prepared", evidence_index_hash=identity,
                structured_context_hash=audit["structured_context_hash"],
                source_catalogue_hash=audit["source_catalogue_hash"],
                policy_version=audit["policy"]["version"],
                product_binding_status_counts=audit["product_binding_status_counts"],
                unknown_structured_fields=audit["unknown_structured_fields"])
        elif indexes[identity] != index:
            raise WorkflowFailure("frozen rule evidence index changed")
        return deepcopy(shared)

    def physician_transcript(self):
        """Conversation personally available to the physician, separate from audit."""
        return deepcopy([segment for segment in self.transcript
                         if segment.get("phase") in PHYSICIAN_DIALOGUE_PHASES])

    @staticmethod
    def verify_physician_transcript(transcript):
        if not isinstance(transcript, list) or any(not isinstance(segment, dict) or
                segment.get("phase") not in PHYSICIAN_DIALOGUE_PHASES for segment in transcript):
            raise WorkflowFailure("clinical source transcript contains dialogue outside physician visibility")

    def begin_consultation(self, *, load_measurement_panel=True):
        begun = self.perform("encounter.begin_consultation", {}, "doctor")
        if str(begun.get("encounter_id")) != str(self.context["encounter_id"]):
            raise WorkflowFailure("consultation start does not match registered encounter")
        if load_measurement_panel:
            # These are already-recorded current measurements released at the
            # consultation boundary, not new tests or inferred historical values.
            page = self.perform("history.query", {"section": "current_observations", "offset": 0,
                "limit": CURRENT_MEASUREMENT_POLICY["max_records"]}, "doctor", write=False).get("page")
            if (not isinstance(page, dict) or page.get("section") != "current_observations" or
                    not isinstance(page.get("records"), list) or json_bytes(page) > PAGE_BYTE_LIMIT):
                raise WorkflowFailure("invalid current measurement panel readback")
            panel = {"records": [], "source_section": "current_observations",
                "source_operation": "history.query", "readback_verified": True,
                "available_at": "physician_consultation", "observed_at": _utc(),
                "queried_after_sequence": self.transcript[-1]["sequence"] if self.transcript else 0,
                "time_basis": deepcopy(page.get("time_basis")),
                "unshown_is_not_absent": True, "withheld_or_oversize_returned_records": 0,
                "next_offset": page.get("next_offset"), "total_count": page.get("total_count")}
            for row in page["records"]:
                if not isinstance(row, dict) or not isinstance(row.get("record_ref"), str):
                    raise WorkflowFailure("current measurement lacks a record reference")
                if row.get("record", {}).get("available_at") != "physician_consultation":
                    panel["withheld_or_oversize_returned_records"] += 1
                    continue
                candidate = {**panel, "records": panel["records"] + [deepcopy(row)]}
                if json_bytes(candidate) > CURRENT_MEASUREMENT_POLICY["max_bytes"]:
                    panel["withheld_or_oversize_returned_records"] += 1
                    continue
                panel["records"].append(deepcopy(row))
            self.current_measurement_panel = panel
            self.result["artifacts"]["current_encounter_measurements"] = deepcopy(panel)
            self.event("current_measurement_panel_read", returned_refs=[row["record_ref"] for row in panel["records"]],
                returned_count=len(panel["records"]), source_section="current_observations",
                readback_verified=True, manual_history_query_budget_consumed=False,
                withheld_or_oversize_returned_records=panel["withheld_or_oversize_returned_records"])

    def consult(self):
        self.consultation_interactions_used=0
        self.begin_consultation()
        # A short visit still has a direct physician exchange. The opening
        # question is a common clinic protocol; the patient generates its answer.
        if not self.physician_transcript():
            self.activity("doctor", "diagnostic")
            self.ask_patient("doctor", CONSULTATION_DIALOGUE_POLICY["opening_question"], "consultation")
            self.event("standard_consultation_opening_completed",
                       policy=CONSULTATION_DIALOGUE_POLICY["version"])
        draft_prefix_length = 0
        if self.realtime_condition is not None:
            prefix = self.physician_transcript()[:2]
            self.documentation(self.realtime_condition, prefix, {}, {}, finalize=False)
            draft_prefix_length = len(prefix)
        turn = 0
        while turn <= self.runner.limits["consultation_turns"]:
            self.consultation_interactions_used=turn
            response = self.respond("doctor", {"action": "consult", **self.clinical_context(),
                "formulary": deepcopy(self.case["formulary"]),
                "diagnosis_catalogue": deepcopy(self.diagnosis_catalogue),
                "remaining_history_queries": self.history_queries_remaining("consultation"),
                "remaining_interactions": self.runner.limits["consultation_turns"]-turn}, phase="consultation")
            if response.get("action") == "read_history":
                self.read_history(response, "consultation")
                continue
            if response.get("action") == "consultation_complete":
                normalized, code_changes = canonicalize(response.get('diagnoses'), self.diagnosis_catalogue)
                if code_changes:
                    original = deepcopy(response)
                    response = {**deepcopy(response), 'diagnoses': normalized}
                    mapping = {'policy': deepcopy(DIAGNOSIS_CODE_POLICY),
                        'original_response': original, 'original_response_hash': digest(original),
                        'canonical_response_hash': digest(response), 'changes': code_changes,
                        'catalogue_hash': digest(self.diagnosis_catalogue)}
                    self.result['artifacts'].setdefault('diagnosis_code_normalizations', []).append(mapping)
                    self.event('diagnosis_code_display_normalized',
                        original_response_hash=digest(original), canonical_response_hash=digest(response),
                        policy_version=DIAGNOSIS_CODE_POLICY['version'], changes=code_changes,
                        clinical_decision_changed=False)
                candidate = response.get("prescription")
                if not isinstance(candidate, dict) or not isinstance(candidate.get("items"), list):
                    raise WorkflowFailure("physician prescription must contain an explicit items list")
                if candidate["items"]:
                    validate_prescription(candidate)
                # An unfinished assessment is evidence, not the end of the
                # hospital work queue. Keep it immutable and perform a distinct
                # staff service before returning new findings to this physician.
                # The bounded service deduplicates its request, so an unchanged
                # no-Rx answer is never repeatedly sampled until it becomes Rx.
                if not candidate['items'] and self.runner.close_prescription_loop:
                    prior_services = deepcopy((self.consultation_record or {}).get('in_hospital_services', []))
                    self.consultation_record = deepcopy(response)
                    if prior_services:
                        self.consultation_record['in_hospital_services'] = prior_services
                    assessment = {'response': deepcopy(response), 'response_hash': digest(response),
                        'status': 'unfinished_initial_assessment', 'native_prescription_created': False,
                        'new_evidence_required_before_reassessment': True}
                    self.result['artifacts'].setdefault('consultation_assessments', []).append(assessment)
                    request = {'decision': 'defer', 'source': 'actual_physician_initial_assessment',
                        'reason': response.get('no_prescription_reason') or response.get('plan'),
                        'medication_reconciliation': deepcopy(response.get('medication_reconciliation')),
                        'allergy_assessment': deepcopy(response.get('allergy_assessment'))}
                    if self.reconcile_in_hospital(request, candidate):
                        self.event('consultation_returned_after_reconciliation',
                            initial_assessment_hash=digest(response),
                            service_hash=digest(self.result['artifacts']['in_hospital_services'][-1]),
                            same_encounter=True, clinical_decision_changed_by_runtime=False)
                        continue
                prior_services = deepcopy((self.consultation_record or {}).get('in_hospital_services', []))
                self.consultation_record = deepcopy(response)
                if prior_services:
                    self.consultation_record['in_hospital_services'] = prior_services
                self.result["artifacts"]["consultation"] = deepcopy(response)
                diagnoses_mapped = True
                if self.diagnosis_catalogue:
                    diagnoses = response.get("diagnoses")
                    diagnoses_mapped = all_mapped(diagnoses, self.diagnosis_catalogue)
                    if candidate["items"] and (not isinstance(diagnoses, list) or not diagnoses):
                        raise WorkflowFailure("physician did not supply a structured diagnosis")
                    if candidate["items"] and not diagnoses_mapped:
                        raise WorkflowFailure("physician diagnosis is not mapped in the hospital catalogue")
                if diagnoses_mapped:
                    self.perform("consultation.save", {"artifact_id": self.prefix + ":consultation",
                                 "content": response, "transcript": self.physician_transcript()}, "doctor")
                else:
                    # Native diagnosis persistence requires a mapped diagnosis.
                    # An honest no-Rx/undetermined diagnosis remains an audited
                    # clinical decision; never invent a code to satisfy the HIS.
                    self.event("consultation_recorded_without_native_diagnosis", content=deepcopy(response),
                        content_hash=digest(response), persistence="private_local_audit_journal",
                        native_write_attempted=False, reason="no_prescription_and_no_mapped_current_diagnosis")
                    self.result["artifacts"]["consultation_persistence"] = {
                        "clinical_decision_recorded": True, "native_diagnosis_recorded": False,
                        "persistence": "private_local_audit_journal" if self.directory else "in_memory_engineering_test"}
                self.event("consultation_completed", content_hash=digest(response))
                eligibility = {"status": "prescription_observed" if candidate["items"] else
                               "not_applicable_to_observed_decision",
                    "decision": "prescription_issued" if candidate["items"] else "no_prescription_issued",
                    "source": "actual_physician_consultation", "source_response_hash": digest(response),
                    "clinical_appropriateness": "not_assessed_outside_programmatic_scope"}
                if not candidate["items"]:
                    eligibility["stated_reason"] = (response.get("no_prescription_reason") or
                        candidate.get("no_prescription_reason") or response.get("plan"))
                    eligibility["three_task_chain_complete"] = False
                    self.event("prescription_not_issued", disposition="no_prescription_issued",
                               clinical_appropriateness="not_assessed_outside_programmatic_scope")
                self.result["artifacts"]["prescription_eligibility"] = eligibility
                return response
            if response.get("action") != "ask" or turn >= self.runner.limits["consultation_turns"]:
                raise WorkflowFailure("consultation did not finish within the declared limit")
            self.activity("doctor", "diagnostic")
            self.ask_patient("doctor", response.get("question"), "consultation")
            turn += 1
            if self.realtime_condition is not None:
                prefix = self.physician_transcript()
                while len(prefix) - draft_prefix_length >= self.runner.limits["realtime_chunk_segments"]:
                    draft_prefix_length += self.runner.limits["realtime_chunk_segments"]
                    self.documentation(self.realtime_condition, prefix[:draft_prefix_length], {}, {}, finalize=False)
        raise AssertionError("unreachable consultation")

    def review_prescription(self, prescription, condition, context, revision):
        context = self.prepare_rule_context(context)
        rule = self.runner.pprs.review(prescription, context)
        if not isinstance(rule, dict) or rule.get("decision") not in {"pass", "flag", "reject"}:
            raise WorkflowFailure("rule engine returned an invalid review")
        ai = pharmacist = senior = None
        phase = f"prescription_review_{revision}"
        base = {"action": "review_prescription", "prescription": deepcopy(prescription),
                "clinical_context": deepcopy(context), "formulary": deepcopy(self.case["formulary"])}
        if condition.workflow == "parallel":
            # Neither independent reviewer sees the other's judgment.
            self.activity("pharmacist", "prescription_review")
            pharmacist = self.respond("pharmacist", base, phase=phase + ":independent")
            ai = self.respond("rx_ai", base, phase=phase + ":ai", family=condition.model_family)
        elif rule["decision"] != "reject":
            if condition.workflow == "sequential":
                ai = self.respond("rx_ai", base, phase=phase + ":ai", family=condition.model_family)
            if rule["decision"] == "flag" or (ai and ai.get("decision") in {"flag", "reject"}):
                self.activity("pharmacist", "prescription_review")
                pharmacist = self.respond("pharmacist", {**base, "rule_review": rule, "ai_review": ai},
                                          phase=phase + ":flagged_review")
        for review in (ai, pharmacist):
            if review is not None and review.get("decision") not in {"approve", "flag", "reject"}:
                raise WorkflowFailure("invalid prescription reviewer decision")
        # A screening alert is an unresolved question, not a final finding of
        # inappropriate prescribing. Preserve all three reviewer states, also
        # when both branches intercepted the candidate for different reasons.
        automatic_decision = ("reject" if ai and ai["decision"] == "reject" else
            "flag" if rule["decision"] == "flag" or (ai and ai["decision"] == "flag") else "approve")
        if rule["decision"] == "reject":
            decision = "reject"
        elif condition.workflow == "parallel" and automatic_decision != pharmacist["decision"]:
            self.activity("senior_pharmacist", "prescription_adjudication")
            senior = self.respond("senior_pharmacist", {"action": "adjudicate", **base,
                "action": "adjudicate", "reviews": [rule, ai, pharmacist],
                "required_response": {"action": "adjudication", "decision": ["approve", "reject", "defer"],
                                      "reason": "string"},
                "defer_semantics": "Unresolved clinical disposition; do not convert uncertainty to approval or rejection."},
                phase=phase + ":adjudication")
            if senior.get("decision") not in {"approve", "reject", "defer"}:
                self.result["artifacts"]["unresolved_prescription_adjudication"] = {
                    "status": "invalid_response_contract", "response": deepcopy(senior),
                    "prescription_hash": digest(prescription), "clinical_appropriateness": "not_assessed_outside_programmatic_scope"}
                raise WorkflowFailure("senior pharmacist did not return a disposition")
            decision = senior["decision"]
        elif pharmacist:
            decision = "defer" if pharmacist["decision"] == "flag" else pharmacist["decision"]
        else:
            decision = "defer" if automatic_decision == "flag" else automatic_decision
        review = {"rule_review": rule, "ai_review": ai, "pharmacist_review": pharmacist,
                  "senior_review": senior, "decision": decision, "prescription_hash": digest(prescription),
                  "revision": revision, "condition": condition.to_dict(),
                  "resolution_policy": "preserve_approve_reject_unresolved_v2"}
        self.event("prescription_reviewed", **review)
        return review

    def continue_frozen_prescription(self, stage_input, condition, state):
        """Keep the first-review endpoint, then execute real repair in this branch.

        Only the pre-review source snapshot is restored. The source encounter's
        later pharmacist decisions, final note and payment are never shown.
        """
        context = deepcopy(stage_input.get("clinical_context"))
        if not isinstance(context, dict) or not isinstance(state, dict):
            raise WorkflowFailure("prescription continuation requires frozen context and observed budget state")
        used = state.get("consultation_interactions_used")
        counts = state.get("history_query_counts")
        if (type(used) is not int or not 0 <= used <= self.runner.limits["consultation_turns"]
                or not isinstance(counts, dict)
                or any(k not in PHYSICIAN_DIALOGUE_PHASES or type(v) is not int
                       or not 0 <= v <= self.runner.limits["history_queries_per_phase"] for k,v in counts.items())
                or state.get("stage_input_hash") != digest(stage_input)):
            raise WorkflowFailure("invalid or unbound continuation budget state")
        self.restore_frozen_history(context.get("hospital_history"))
        self.verify_physician_transcript(context.get("conversation"))
        self.transcript = deepcopy(context["conversation"])
        if any(type(x.get('sequence')) is not int for x in self.transcript) or [x['sequence'] for x in self.transcript] != sorted({x['sequence'] for x in self.transcript}):
            raise WorkflowFailure("invalid frozen conversation sequence")
        self.handoff = deepcopy(context.get("handoff"))
        self.current_measurement_panel = deepcopy(context.get("current_encounter_measurements"))
        self.consultation_record = deepcopy(context.get("consultation"))
        variant=getattr(self,'controlled_variant',None)
        physician_proposal=(variant['source_stage_input']['prescription'] if variant else stage_input.get('prescription'))
        if not isinstance(self.consultation_record, dict) or self.consultation_record.get("prescription") != physician_proposal:
            raise WorkflowFailure("frozen consultation does not contain the original prescription")
        if variant:
            if context!=variant['source_stage_input']['clinical_context']:
                raise WorkflowFailure('order-entry intervention changed the source consultation context')
            self.event('controlled_order_entry_intervention',variant_id=variant['variant_id'],
                source_stage_input_hash=variant['source_stage_input_hash'],
                candidate_stage_input_hash=variant['stage_input_hash'],
                original_physician_proposal_preserved=True,counts_as_new_patient=False)
        self.consultation_interactions_used = used
        self.history_query_counts = deepcopy(counts)
        self.result['artifacts'].update(consultation=deepcopy(self.consultation_record),
            physician_verified_handoff=deepcopy(self.handoff),
            current_encounter_measurements=deepcopy(self.current_measurement_panel))
        followthrough = {"status": "running", "source_state": deepcopy(state),
            "primary_endpoint_unchanged": True, "counts_as_new_complete_encounter": False,
            "clinical_appropriateness": "not_assessed_outside_programmatic_scope"}
        self.result["artifacts"]["prescription_followthrough"] = followthrough
        self.event("frozen_prescription_continuation_started", source_state_hash=digest(state),
            stage_input_hash=digest(stage_input), original_review_not_yet_performed=True)
        self.perform("consultation.save", {"artifact_id": self.prefix + ":consultation",
            "content": self.consultation_record, "transcript": self.physician_transcript()}, "doctor")
        documentation = TaskCondition("documentation", "manual_documentation")
        try:
            final_rx = self.prescription(validate_prescription(stage_input["prescription"]),
                condition, revise=True, fixed_context=context)
        except ClinicalDecisionIncomplete as clinical_stop:
            self.document_clinical_disposition(documentation, clinical_stop)
            followthrough.update(status="unresolved_in_hospital_documented" if
                self.result['artifacts'].get('disposition_documentation_outcome',{}).get('status') == 'attested'
                and self.result['artifacts'].get('final_care_plan_outcome',{}).get('status') == 'recorded'
                else "disposition_incomplete", drug_payment_completed=False)
            raise
        if final_rx is None:
            raise WorkflowFailure("prescription continuation returned without a disposition")
        self.result['stage_inputs']['documentation'] = {
            "transcript": self.physician_transcript(), "handoff": deepcopy(self.handoff),
            "consultation": deepcopy(self.consultation_record), "hospital_history": deepcopy(self.history),
            "current_encounter_measurements": deepcopy(self.current_measurement_panel),
            "observed_business_state": {"prescription": deepcopy(self.prescription_business_state)},
            "approved_prescription": deepcopy(final_rx)}
        self.documentation(documentation, self.physician_transcript(), self.consultation_record, final_rx)
        self.settle()
        followthrough.update(status="approved_documented_and_paid", drug_payment_completed=True,
            final_prescription_hash=digest(final_rx), final_note_hash=digest(self.result['artifacts']['attested_note']))
        self.event("prescription_followthrough_completed", outcome_hash=digest(followthrough),
            counts_as_new_complete_encounter=False)

    def reconcile_in_hospital(self, review, prescription):
        """A real bounded staff task, not a retry of the same review decision."""
        if self.in_hospital_reconciliation_requests >= self.runner.limits['in_hospital_reconciliation_requests']:
            return False
        if any(s['requested_review_hash']==digest(review) and s['prescription_hash']==digest(prescription)
                for s in self.result['artifacts'].get('in_hospital_services',[])):
            return False  # Never repeat the same service to fish for a preferred answer.
        self.in_hospital_reconciliation_requests += 1
        number=self.in_hospital_reconciliation_requests
        phase=f'in_hospital_reconciliation_{number}'
        questions_used=0
        self.activity('pharmacist','prescription_review')
        while True:
            answer=self.respond('pharmacist',{'action':'reconcile_medications',
                'clinical_context':self.clinical_context(),'prescription':deepcopy(prescription),
                'requested_issues':deepcopy(review),'formulary':deepcopy(self.case['formulary']),
                'reconciliation_conversation':[deepcopy(s) for s in self.transcript if s.get('phase')==phase],
                'remaining_history_queries':self.history_queries_remaining(phase),
                'remaining_interactions':self.runner.limits['reconciliation_turns']-questions_used,
                'scope':'Provide an in-hospital medication/allergy reconciliation for the physician, not a prescription approval. Use the actual visible chart and patient report; distinguish reported current use, historical orders, unknowns and your assessment. Source research-review status is not itself a clinical information gap. Staff, drug stock and equipment are available here. Do not require an outside referral or invent missing laboratory results. Query or ask only to resolve the named issue.'},phase=phase)
            if answer.get('action')=='read_history':
                self.read_history(answer,phase,actor_role='pharmacist')
            elif answer.get('action')=='ask':
                if questions_used >= self.runner.limits['reconciliation_turns']:
                    raise WorkflowFailure('In-hospital reconciliation exceeded its declared question budget')
                self.activity('pharmacist','information_collection')
                self.ask_patient('pharmacist',answer.get('question'),phase)
                questions_used += 1
            else:
                service={'service_id':self.prefix+f':reconciliation:{number}',
                    'service':'in_hospital_medication_reconciliation','number':number,
                    'requested_review_hash':digest(review),'prescription_hash':digest(prescription),
                    'questions_used':questions_used,'history_queries_used':self.history_query_counts.get(phase,0),
                    'response':deepcopy(answer),'response_hash':digest(answer),
                    'source':'actual_pharmacist_role_assessment_not_database_truth',
                    'clinical_appropriateness':'not_assessed_outside_programmatic_scope',
                    'prescription_approval_changed':False,'external_transfer_performed':False}
                self.result['artifacts'].setdefault('in_hospital_services',[]).append(deepcopy(service))
                self.consultation_record.setdefault('in_hospital_services',[]).append(deepcopy(service))
                self.event('in_hospital_reconciliation_completed',service_id=service['service_id'],
                    service_hash=digest(service),original_review_unchanged=True)
                return True

    def prescription(self, original, condition, *, revise, fixed_context=None):
        prescription = deepcopy(original)
        context = deepcopy(fixed_context) if fixed_context is not None else self.clinical_context()
        context = self.prepare_rule_context(context)
        assert_visible(context)
        if isinstance(context, dict) and "conversation" in context:
            self.verify_physician_transcript(context["conversation"])
        self.result["artifacts"]["original_prescription"] = deepcopy(original)
        versions = self.result["artifacts"].setdefault("prescription_versions", [])
        parent_order = None
        parent_native_order = None
        formulary_codes={p['drug_code'] for p in self.case['formulary']}
        maximum = self.runner.limits["prescription_revisions"] if revise else 0
        for revision in range(maximum + 1):
            self.order_id = self.prefix + f":order:{revision}"
            unmapped=sorted({i['drug_code'] for i in prescription['items'] if i['drug_code'] not in formulary_codes})
            business_validation={'status':'unmapped_product' if unmapped else 'catalogue_codes_present',
                'unsupported_codes':unmapped,'clinical_appropriateness':'not_assessed',
                'automatic_substitution':False}
            encoding_check=getattr(self.runner.backend,'preflight_order',None)
            if encoding_check is not None:
                encoding=encoding_check(prescription)
                if (not isinstance(encoding,dict) or type(encoding.get('native_encodable')) is not bool
                        or encoding.get('native_write_attempted') is not False):
                    raise WorkflowFailure('Native order preflight returned an invalid contract')
                business_validation['native_encoding']=deepcopy(encoding)
                if encoding['native_encodable'] is False:
                    business_validation['status']='native_encoding_unavailable'
            encodable=not unmapped and business_validation.get('native_encoding',{}).get('native_encodable',True)
            save_native=revise and encodable
            if save_native:
                self.perform("order.save", {"order_id": self.order_id, "items": prescription["items"],
                             "parent_order_id": parent_native_order}, "doctor")
            else:
                # A deliberately malformed candidate must reach the clinical
                # reviewer even if the native catalogue cannot store its route.
                # It is durable local audit evidence, never a claimed native order.
                self.event("prescription_candidate_recorded", candidate_id=self.order_id,
                    prescription=deepcopy(prescription), prescription_hash=digest(prescription),
                    persistence="private_local_audit_journal" if self.directory else "in_memory_engineering_test",
                    native_write_attempted=False,business_validation=deepcopy(business_validation))
            review = self.review_prescription(prescription, condition, context, revision)
            versions.append({"order_id": self.order_id, "parent_order_id": parent_order,
                             "version": revision+1, "prescription": deepcopy(prescription), "review": review,
                             "native_write_attempted": save_native,'native_parent_order_id':parent_native_order,
                             'business_validation':deepcopy(business_validation)})
            if revision == 0:
                # The scored outcome always belongs to the original candidate, even after successful repair.
                self.result["artifacts"]["original_prescription_review"] = deepcopy(review)
            if review["decision"] == "defer":
                source = next((name for name in ("senior_review", "pharmacist_review", "ai_review", "rule_review")
                               if review.get(name) is not None), "rule_review")
                self.result["artifacts"]["unresolved_prescription_adjudication"] = {
                    "status": "deferred", "response": deepcopy(review[source]), "response_source": source,
                    "prescription_hash": digest(prescription), "clinical_appropriateness": "not_assessed_outside_programmatic_scope"}
                if not revise or revision >= maximum:
                    raise ClinicalDecisionIncomplete("prescription review remains unresolved; no approval, rejection or settlement inferred")
                # A fixed-input stage stops at its original disposition. A full
                # encounter can send this actual feedback to the physician using
                # the same existing revision budget as a rejection. No flag is
                # changed into a rejection, approval or new scored candidate.
                self.event("prescription_feedback_returned", disposition="defer",
                    revision=revision, remaining_revisions=maximum-revision,
                    prescription_hash=digest(prescription), review_hash=digest(review))
            if review["decision"] == "approve" and not (revise and not encodable):
                prior_unresolved=self.result['artifacts'].pop('unresolved_prescription_adjudication',None)
                if prior_unresolved is not None:
                    self.result['artifacts'].setdefault('resolved_prescription_adjudications',[]).append({
                        'previous_unresolved_record':prior_unresolved,
                        'resolution_review_hash':digest(review),'resolved_at_revision':revision})
                if revise:
                    registry = self.perform("personnel.registry", {}, "doctor", write=False)
                    signatory_id = registry.get("signatory_id")
                    if not isinstance(signatory_id, (str, int)) or isinstance(signatory_id, bool) or not str(signatory_id):
                        raise WorkflowFailure("authenticated physician registry did not return a signatory")
                    state = self.perform("order.attest", {"order_id": self.order_id,
                                         "signatory_id": signatory_id}, "doctor")
                    if state.get("status") != "signed":
                        raise WorkflowFailure("order signature not confirmed")
                    # This is observed application state, distinct from whether a
                    # prescription is clinically correct or should later change.
                    self.prescription_business_state = {
                        "logical_order_id": self.order_id, "status": state["status"],
                        "items": deepcopy(prescription["items"]), "readback_verified": True,
                        "observed_at": _utc(), "source_operation": "order.attest",
                        "signatory_verified_from_registry": True, "registry_version": registry.get("registry_version")}
                    self.result["artifacts"]["prescription_business_state"] = deepcopy(self.prescription_business_state)
                self.result["artifacts"]["final_prescription"] = deepcopy(prescription)
                return prescription
            if revision >= maximum:
                if revise:
                    if not encodable:
                        raise WorkflowFailure('Unencodable proposed medication remained after bounded feedback; no native order or settlement')
                    self.result["artifacts"]["prescription_termination"] = {
                        "status": "review_unresolved_at_fixed_revision_limit",
                        "final_review": deepcopy(review), "prescription_hash": digest(prescription),
                        "completed_revisions": revision, "maximum_revisions": maximum,
                        "clinical_appropriateness": "not_assessed_outside_programmatic_scope",
                        "three_task_chain_complete": False}
                    self.event("prescription_clinically_incomplete",
                        disposition="review_unresolved_at_fixed_revision_limit", revision=revision,
                        prescription_hash=digest(prescription), review_hash=digest(review))
                    raise ClinicalDecisionIncomplete("prescription remained rejected at the fixed revision limit; no settlement")
                # A fixed-input review task can validly finish by rejecting its
                # original candidate; it does not claim a complete encounter.
                return None
            if (revision > 0 and review['decision'] == 'defer' and self.runner.close_prescription_loop
                    and self.reconcile_in_hospital(review, prescription)):
                context = self.prepare_rule_context(self.clinical_context())
            self.activity("doctor", "prescription_revision")
            while True:
                answer = self.respond("doctor", {"action": "revise_prescription", "prescription": prescription,
                    "clinical_context": context, "hospital_history":deepcopy(self.history),
                    "business_validation":deepcopy(business_validation),
                    "reviews": review, "formulary": self.case["formulary"],
                    "remaining_revisions":maximum-revision,
                    "remaining_history_queries":self.history_queries_remaining('consultation'),
                    "remaining_interactions":self.runner.limits['consultation_turns']-self.consultation_interactions_used,
                    "review_state":review['decision'],
                    "followup_scope":(
                        "Respond to the actual review. Read existing chart records or ask the patient within "
                        "the remaining consultation budgets. Assess each proposed item and its interactions "
                        "with the patient's reported current regimen before deferring the whole order. "
                        "If a specific item needs more evidence, you may withhold it and resubmit the "
                        "independently justified items when they can be safely assessed. Explain what was "
                        "withheld, why, and any needed follow-up in reason. Withholding a proposed refill "
                        "does not prove that the patient stopped taking the medicine. If a dispensing prerequisite "
                        "is still unmet, put that item in the pending plan described in reason. Do not include it in an "
                        "order submitted for immediate dispensing with an instruction to wait for the same check. "
                        "Use a verified alternative only when clinically justified. Defer the entire order "
                        "if unresolved evidence also prevents assessment of every remaining option. "
                        "Every resubmitted order receives a fresh review. Use only available evidence."),
                    },
                    phase=f"prescription_revision_{revision}")
                if answer.get('action')=='read_history':
                    self.read_history(answer,'consultation')
                elif answer.get('action')=='ask':
                    if self.consultation_interactions_used>=self.runner.limits['consultation_turns']:
                        raise WorkflowFailure('Prescription follow-up exceeded the shared consultation question limit')
                    self.activity('doctor','diagnostic')
                    self.ask_patient('doctor',answer.get('question'),'consultation')
                    self.consultation_interactions_used+=1
                    self.event('prescription_followup_question',revision=revision,
                        remaining_interactions=self.runner.limits['consultation_turns']-self.consultation_interactions_used)
                elif answer.get('decision') in {'defer','retain_rejected'} and self.runner.close_prescription_loop:
                    self.result['artifacts'].setdefault('physician_unresolved_decisions',[]).append({
                        'revision':revision,'response':deepcopy(answer),'response_hash':digest(answer),
                        'routed_to':'in_hospital_reconciliation','not_an_approval':True})
                    if not self.reconcile_in_hospital(review,prescription):break
                else:break
                context=self.prepare_rule_context(self.clinical_context())
            if answer.get('decision') == 'defer':
                self.result['artifacts']['prescription_termination']={
                    'status':'physician_deferred_after_review','physician_response':deepcopy(answer),
                    'review':deepcopy(review),'prescription_hash':digest(prescription),'revision':revision,
                    'clinical_appropriateness':'not_assessed_outside_programmatic_scope','three_task_chain_complete':False}
                self.event('prescription_clinically_incomplete',disposition='physician_deferred_after_review',
                    revision=revision,prescription_hash=digest(prescription),physician_response_hash=digest(answer))
                raise ClinicalDecisionIncomplete('physician deferred after review; no order signature or settlement')
            if answer.get("decision") == "retain_rejected":
                self.result["artifacts"]["prescription_termination"] = {
                    "status": "physician_retained_rejected_prescription" if review['decision']=='reject' else 'physician_retained_unapproved_prescription',
                    "physician_response": deepcopy(answer), "review": deepcopy(review),
                    "prescription_hash": digest(prescription), "revision": revision,
                    "clinical_appropriateness": "not_assessed_outside_programmatic_scope",
                    "three_task_chain_complete": False}
                self.event("prescription_clinically_incomplete",
                    disposition="physician_retained_rejected_prescription", revision=revision,
                    prescription_hash=digest(prescription), physician_response_hash=digest(answer))
                raise ClinicalDecisionIncomplete("physician retained the rejected prescription; no new order or settlement")
            if answer.get("decision") != "revise":
                raise WorkflowFailure("physician returned an invalid revision response")
            if isinstance(answer.get('prescription'), dict) and answer['prescription'].get('items') == []:
                self.result['artifacts']['prescription_termination'] = {
                    'status': 'physician_withheld_after_review', 'physician_response': deepcopy(answer),
                    'review': deepcopy(review), 'prescription_hash': digest(prescription), 'revision': revision,
                    'clinical_appropriateness': 'not_assessed_outside_programmatic_scope', 'three_task_chain_complete': False}
                self.event('prescription_clinically_incomplete', disposition='physician_withheld_after_review',
                    revision=revision, physician_response_hash=digest(answer))
                raise ClinicalDecisionIncomplete('physician explicitly withheld prescription after review; no drug payment')
            followup={'revision':revision,'review_hash':digest(review),
                'previous_prescription_hash':digest(prescription),'physician_response':deepcopy(answer),
                'source':'actual_physician_revision_response','persistence':'runtime_journal_not_native_consultation_update',
                'clinical_appropriateness':'not_assessed_outside_programmatic_scope'}
            self.result['artifacts'].setdefault('prescription_followups',[]).append(deepcopy(followup))
            # All next reviewers see the physician's actual response, not merely
            # an unexplained new order. It remains an agent-reported statement.
            self.consultation_record.setdefault('prescription_review_followups',[]).append(deepcopy(followup))
            prescription = validate_prescription(answer.get("prescription"))
            context=self.prepare_rule_context(self.clinical_context())
            parent_order = self.order_id
            if save_native:parent_native_order=self.order_id
        return None

    def document_clinical_disposition(self, condition, clinical_stop):
        """Write the actual non-prescribing decision without completing/charging the chain."""
        artifacts = self.result["artifacts"]
        trigger = next((call["phase"] for call in reversed(self.calls)), "clinical_decision")
        self.clinical_disposition = {
            "status": "incomplete_clinical_decision", "trigger_phase": trigger,
            "reason": str(clinical_stop), "prescription_eligibility": deepcopy(artifacts.get("prescription_eligibility")),
            "prescription_termination": deepcopy(artifacts.get("prescription_termination")),
            "unresolved_adjudication": deepcopy(artifacts.get("unresolved_prescription_adjudication")),
            "original_candidate": deepcopy(artifacts.get("original_prescription")),
            "original_review": deepcopy(artifacts.get("original_prescription_review")),
            "approved_prescription_available": False, "drug_settlement_attempted": False,
            "clinical_appropriateness": "not_assessed_outside_programmatic_scope"}
        artifacts["clinical_disposition"] = deepcopy(self.clinical_disposition)
        if self.runner.close_prescription_loop:
            # A bare defer is not a patient-facing outcome. Ask for the next
            # clinical action, preserving unavailable evidence and all reviews.
            # This is one distinct planning action, not another attempt to obtain
            # an approval or to generate a convenient laboratory result.
            outcome = {"status": "pending", "planned_actions_executed": False,
                "drug_order_signed": False, "drug_payment_completed": False}
            artifacts['final_care_plan_outcome'] = outcome
            try:
                self.activity('doctor', 'prescription_revision')
                plan = self.respond('doctor', {'action': 'finalize_care_plan',
                    **self.clinical_context(), 'clinical_disposition': deepcopy(self.clinical_disposition),
                    'scope': 'This remains unfinished within the virtual hospital. State the exact remaining clinical information or unimplemented service needed here, and the responsible in-hospital role. Staff, drugs and equipment are nonbinding resources. Do not refer outside, claim that planned tests occurred, or count this plan/locked note as a completed visit. Do not approve the unapproved order or invent a measurement.'},
                    phase='final_care_plan')
                artifacts['final_care_plan'] = deepcopy(plan)
                self.clinical_disposition['final_care_plan'] = deepcopy(plan)
                artifacts['clinical_disposition'] = deepcopy(self.clinical_disposition)
                outcome.update(status='recorded', response_hash=digest(plan),
                    persistence='runtime_journal_then_attested_note', native_referral_or_test_order_created=False)
            except Exception as exc:
                outcome.update(status=('stopped_budget' if type(exc).__name__ == 'BudgetExceeded' else
                    'stopped_provider' if type(exc).__name__ == 'ProviderUnavailable' else 'failed'),
                    error_type=type(exc).__name__, reason=str(exc)[:600])
                if type(exc).__name__ in {'BudgetExceeded','ProviderUnavailable'}:
                    raise
            finally:
                self.event('final_care_plan_recorded', outcome=deepcopy(outcome))
        self.result["three_task_eligible"] = False
        self.result["documentation_input_eligibility"] = "documentation_only_actual_clinical_disposition"
        source = {"transcript": self.physician_transcript(), "handoff": deepcopy(self.handoff),
            "consultation": deepcopy(self.consultation_record), "hospital_history": deepcopy(self.history),
            "current_encounter_measurements": deepcopy(self.current_measurement_panel),
            "observed_business_state": {"prescription": deepcopy(self.prescription_business_state)},
            "approved_prescription": {"items": []}, "clinical_disposition": deepcopy(self.clinical_disposition)}
        self.result["stage_inputs"]["documentation"] = source
        outcome = {"status": "not_started", "input_hash": digest(source),
            "qualifies_complete_three_task_chain": False, "drug_settlement_attempted": False}
        artifacts["disposition_documentation_outcome"] = outcome
        try:
            self.documentation(condition, source["transcript"], source["consultation"], source["approved_prescription"])
            outcome.update(status="attested", note_hash=digest(artifacts["attested_note"]),
                clinical_quality="not_assessed_outside_programmatic_scope")
        except Exception as exc:
            outcome.update(status=('stopped_budget' if type(exc).__name__ == 'BudgetExceeded' else
                'stopped_provider' if type(exc).__name__ == 'ProviderUnavailable' else 'failed'),
                error_type=type(exc).__name__, failure_reason=str(exc)[:1000])
            if type(exc).__name__ in {'BudgetExceeded','ProviderUnavailable'}:
                raise
        finally:
            self.event("clinical_disposition_documented", status=outcome["status"],
                source_hash=digest(source), outcome_hash=digest(outcome),
                qualifies_complete_three_task_chain=False, drug_settlement_attempted=False)

    def documentation(self, condition, transcript, consultation, prescription, *, finalize=True):
        transcript = deepcopy(transcript)
        self.verify_physician_transcript(transcript)
        sequences = [x.get("sequence") for x in transcript]
        if any(type(x) is not int for x in sequences) or sequences != sorted(set(sequences)):
            raise WorkflowFailure("transcript sequences must be unique and increasing")
        if not transcript and not (self.handoff or consultation):
            raise WorkflowFailure("documentation requires a visible handoff, consultation or dialogue")
        note_id = self.prefix + ":note"
        version = self.note_state["version"] if self.note_state else 0
        content = deepcopy(self.note_state["content"]) if self.note_state else None
        versions = self.result["artifacts"].setdefault("note_versions", [])
        manual = condition.workflow == "manual_documentation"
        chunk = self.runner.limits["realtime_chunk_segments"]
        replay = condition.workflow == "realtime" and finalize and self.realtime_condition is None
        # An interim draft may contain the same dialogue as the final draft in
        # a short visit, but only the latter sees the final decision and order.
        stops = ([(n, False) for n in range(2, len(transcript) + 1, chunk)]
                 if replay else []) + [(len(transcript), finalize)]
        for stop, final in stops:
            prefix = transcript[:stop]
            visible_history = deepcopy(self.history)
            if not final:
                last_sequence = prefix[-1]["sequence"] if prefix else 0
                visible_history["queried_pages"] = [entry for entry in visible_history["queried_pages"]
                    if entry["queried_after_sequence"] < last_sequence]
                visible_history["last_query_feedback"] = None
            source = {"transcript": prefix, "hospital_history": visible_history,
                      "handoff": deepcopy(self.handoff),
                      "current_encounter_measurements": deepcopy(self.current_measurement_panel)
                        if self.current_measurement_panel and (final or self.current_measurement_panel["queried_after_sequence"] <
                            (prefix[-1]["sequence"] if prefix else 0)) else None,
                      "is_final_prefix": final,
                      "allowed_source_scope": {"source_sequences": [x["sequence"] for x in prefix],
                          "consultation_and_signed_prescription_available": bool(final and consultation and self.prescription_business_state),
                          "consultation_available": bool(final and consultation),
                          "signed_prescription_available": bool(final and self.prescription_business_state),
                          "review_standard": "final_documentation" if final else "interim_visible_facts_only",
                          "future_information_required": False},
                      "observed_business_state": {"prescription": deepcopy(self.prescription_business_state) if final else None},
                      "clinical_disposition": deepcopy(self.clinical_disposition) if final else None,
                      "consultation": consultation if final else None,
                      "approved_prescription": prescription if final else None}
            role = "doctor" if manual else "scribe"
            if manual:
                self.activity(role, "documentation")
            draft = self.respond(role, {"action": "document", **source, "previous_draft": content,
                                      "is_final_prefix": final}, phase=f"documentation_draft_{stop}",
                                  family=condition.model_family)
            content = draft.get("content")
            if not isinstance(content, dict) or not isinstance(content.get("text"), str):
                raise WorkflowFailure("note draft requires independent content.text")
            def save(new_content, author, reason):
                nonlocal version
                op = "note.save" if version == 0 else "note.revise"
                state = self.perform(op, {"note_id": note_id, "content": new_content,
                    "expected_version": version, "parent_version": version or None}, author)
                if state.get("version") != version+1:
                    raise WorkflowFailure("note version read-back mismatch")
                version += 1
                versions.append({"version": version, "content": deepcopy(new_content), "author_role": author,
                                 "source_sequences": [x["sequence"] for x in prefix], "reason": reason})
            save(content, role, "initial_draft" if not versions else "incremental_generation")
            accepted = False
            for review_index in range(self.runner.limits["max_note_revisions"] + 1):
                self.activity("doctor", "note_review")
                review = self.respond("doctor", {"action": "review_note", **source,
                    "content": content, "version": version,
                    "remaining_note_revisions": self.runner.limits["max_note_revisions"] - review_index,
                    "current_note_identity": {"version": version, "content_hash": digest(content)},
                    "review_context_policy": deepcopy(NOTE_REVIEW_CONTEXT_POLICY),
                    "previous_review_index": [{k: deepcopy(r[k]) for k in
                        ("reviewed_version", "content_hash", "source_sequences", "is_final_prefix")}
                        for r in self.note_review_history]}, phase=f"note_review_{stop}_{review_index}")
                review_record = {"reviewed_version": version, "content_hash": digest(content),
                    "source_sequences": [x["sequence"] for x in prefix], "is_final_prefix": final,
                    "decision": review.get("decision"), "reason": review.get("reason")}
                self.note_review_history.append(deepcopy(review_record))
                self.result["artifacts"].setdefault("note_reviews", []).append({
                    **review_record, "response": deepcopy(review), "revision_saved": False})
                if review.get("decision") == "accept":
                    accepted = True
                    break
                if review.get("decision") != "revise" or not isinstance(review.get("content"), dict):
                    raise WorkflowFailure("physician rejected note or returned an invalid review")
                content = review["content"]
                if not isinstance(content.get("text"), str):
                    raise WorkflowFailure("note revision requires text")
                if review_index >= self.runner.limits["max_note_revisions"]:
                    # Keep the proposed text in the response audit, but do not
                    # create a business version that cannot receive its review.
                    break
                self.activity("doctor", "note_rework")
                save(content, "doctor", "physician_revision")
                self.result["artifacts"]["note_reviews"][-1]["revision_saved"] = True
            if not accepted:
                raise WorkflowFailure("note review limit exhausted without acceptance")
        self.note_state = {"version": version, "content": deepcopy(content)}
        if not finalize:
            self.event("realtime_note_available_during_consultation", version=version,
                       source_sequences=[x["sequence"] for x in transcript])
            return
        self.activity("doctor", "attestation")
        state = self.perform("note.attest", {"note_id": note_id, "version": version}, "doctor")
        if state.get("status") != "locked":
            raise WorkflowFailure("note attestation not confirmed")
        self.result["artifacts"]["attested_note"] = {"note_id": note_id, "version": version,
            "content": deepcopy(content), "status": "locked"}

    def settle(self):
        bill = self.perform("payment.prepare", {"order_id": self.order_id}, "cashier")
        if not all(key in bill for key in ("bill_id", "amount", "currency")):
            raise WorkflowFailure("pre-settlement did not return an actual bill")
        paid = self.perform("payment.commit", {"bill_id": bill["bill_id"], "amount": bill["amount"],
            "currency": bill["currency"], "channel": "CASH", "transaction_id": self.prefix + ":payment"}, "cashier")
        if paid.get("status") != "paid":
            raise WorkflowFailure("simulated settlement not confirmed")
        self.result["artifacts"]["settlement"] = {"bill": bill, "payment": paid, "simulated": True}

    def execute(self, function, *, conditions, complete=True):
        start = time.monotonic()
        self.result["conditions"] = conditions
        self.result["evaluation_unit"] = "complete_encounter" if complete else "fixed_input_task"
        self.event("run_started", conditions=conditions)
        try:
            function()
            self.result["status"] = "completed"
            self.result["workflow_complete"] = complete
            operations = [e for e in self.events if e["event"] == "business_operation"]
            native = [e for e in operations if e["operation"] == "registration.create" or
                      e["operation"].startswith(("order.", "note.", "payment."))]
            self.result["native_complete"] = bool(complete and native and all(
                e["response"].get("native_effect") is True for e in native))
            self.event("run_completed", native_complete=self.result["native_complete"])
        except KeyboardInterrupt:
            self.result.update(status="failed", workflow_complete=False, error_type="KeyboardInterrupt",
                               failure_reason="Operator interrupted workflow execution")
            self.event("run_interrupted", error_type="KeyboardInterrupt")
            raise
        except Exception as exc:
            # Account/budget stops do not establish a clinical decision.
            status = ("stopped_budget" if type(exc).__name__ == "BudgetExceeded" else
                      "stopped_provider" if type(exc).__name__ == "ProviderUnavailable" else
                      "incomplete_clinical_decision" if isinstance(exc, ClinicalDecisionIncomplete) else "failed")
            self.result.update(status=status, workflow_complete=False,
                               error_type=type(exc).__name__, failure_reason=str(exc)[:1000])
            self.event("run_failed", error_type=type(exc).__name__, reason=str(exc)[:1000])
        finally:
            followthrough=self.result['artifacts'].get('prescription_followthrough')
            if followthrough and followthrough.get('status')=='running':
                followthrough.update(status='not_closed',runtime_status=self.result['status'],
                    drug_payment_completed=False)
            self.result.update(ended_at=_utc(), wall_seconds=time.monotonic()-start,
                               call_count=len(self.calls), activity_count=len(self.activities))
            self.result["history_query_counts"] = deepcopy(self.history_query_counts)
            if self.history is not None:
                self.result["history_coverage"] = {
                    "status": "bounded_selected_records_not_a_complete_chart_read",
                    "queried_page_count": len(self.history["queried_pages"]),
                    "retained_record_refs": sorted({record["record_ref"]
                        for entry in self.history["queried_pages"] for record in entry["page"]["records"]}),
                    "budget_exhausted_phases": [phase for phase in self.history_query_counts
                                               if self.history_queries_remaining(phase) == 0],
                    "unread_page_cursors": [{"section": entry["page"]["section"],
                        "next_offset": entry["page"]["next_offset"]} for entry in self.history["queried_pages"]
                        if entry["page"].get("next_offset") is not None],
                    "unknown_is_not_negative": True}
            self.result["artifacts"]["transcript"] = deepcopy(self.transcript)
            self.result["activities"] = deepcopy(self.activities)
            self.result["events"] = deepcopy(self.events)
            self.result["calls"] = deepcopy(self.calls)
            self.write()
        return deepcopy(self.result)

    def write(self):
        if self.runner.output_dir is None:
            return
        directory = self.directory
        def write(name, value):
            path = directory / name
            path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
            os.chmod(path, 0o600)
        write("run.json", self.result)
        # Appendix trace excludes dialogue, facts, native identifiers and raw backend bodies.
        summary = {k: self.result[k] for k in ("schema_version", "case_id", "group", "data_kind", "split",
                   "config_id", "conditions", "status", "evaluation_unit", "native_complete", "call_count",
                   "wall_seconds", "timing_source")}
        summary["clinical_quality"] = self.result["clinical_quality"]
        summary["note_review_policy"] = self.result["note_review_policy"]
        summary["current_measurement_policy"] = self.result["current_measurement_policy"]
        summary["response_contract_policy"] = self.result["response_contract_policy"]
        summary["clinical_disposition_policy"] = self.result["clinical_disposition_policy"]
        summary["prescription_followthrough_policy"] = self.result["prescription_followthrough_policy"]
        if 'prescription_followthrough' in self.result['artifacts']:
            summary['prescription_followthrough'] = {k:v for k,v in
                self.result['artifacts']['prescription_followthrough'].items()
                if k not in {'source_state'}}
        if "prescription_eligibility" in self.result["artifacts"]:
            summary["prescription_eligibility"] = {k: v for k, v in
                self.result["artifacts"]["prescription_eligibility"].items() if k != "stated_reason"}
        summary["history_query_counts"] = self.result.get("history_query_counts", {})
        summary["history_access_policy"] = self.result.get("history_access_policy")
        summary["history_coverage"] = self.result.get("history_coverage")
        if self.clinical_disposition is not None:
            summary["clinical_disposition"] = {"status": self.clinical_disposition["status"],
                "trigger_phase": self.clinical_disposition["trigger_phase"],
                "clinical_appropriateness": "not_assessed_outside_programmatic_scope",
                "three_task_eligible": False, "drug_settlement_attempted": False}
            summary["disposition_documentation_outcome"] = {k:v for k,v in
                self.result["artifacts"].get("disposition_documentation_outcome", {}).items() if k != "failure_reason"}
        summary["events"] = []
        for event in self.events:
            item = {k: event[k] for k in ("sequence", "event", "operation", "role", "phase", "status",
                    "model_family", "version", "error_type", "payload_hash", "response_hash",
                    "lookup_number", "section", "returned_count", "accepted_into_context", "wall_seconds",
                    "retained_context_bytes", "remaining_visible_bytes", "raw_page_bytes", "projected_page_bytes",
                    "raw_page_hash", "projected_page_hash", "projection_version", "already_visible_record_refs",
                    "new_record_refs", "next_offset", "matching_count", "result_status", "query_hash", "returned_refs", "native_write_attempted") if k in event}
            if event["event"] == "business_operation":
                item.update({k: event["response"].get(k) for k in (
                    "status", "readback_verified", "native_effect", "protection_source")})
            summary["events"].append(item)
        summary["model_calls"] = [{k: call.get(k) for k in ("sequence", "role", "phase", "model_family",
                                  "model_name", "memory_policy", "request_id", "status", "wall_seconds", "usage",
                                  "response_parse",
                                  "schema_correction_attempt", "original_clinical_input_hash", "response_schema_errors")}
                                  for call in self.calls]
        summary["artifact_hashes"] = {k: digest(v) for k, v in self.result["artifacts"].items()}
        # Raw backend errors can contain identifiers or clinical text; keep them only locally.
        summary["error_type"] = self.result.get("error_type")
        summary["failure_stage"] = next((e.get("operation", e.get("phase")) for e in reversed(self.events)
                                          if e["event"] in {"business_operation", "role_call"}), None)
        if self.result["status"] == "incomplete_clinical_decision" and self.clinical_disposition is not None:
            summary["failure_stage"] = self.clinical_disposition["trigger_phase"]
        write("appendix_trace.json", summary)
