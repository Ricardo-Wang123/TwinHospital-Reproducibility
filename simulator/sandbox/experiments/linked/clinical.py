    def respond(self, role, observation, *, phase, family=None):
        if self.medication_directory is None or 'formulary' not in observation:
            return self.role_response(role, observation, phase=phase, family=family)
        directory = self.medication_directory
        observation = {k: v for k, v in observation.items() if k != 'formulary'}
        selected = {}
        frequency_codes = getattr(self.runner.backend, 'order_frequency_codes', None) if self.primary_treatment_only else None

        def orderable(product):
            if frequency_codes is None:
                return product
            return {**product, 'allowed_frequency_codes': frequency_codes(product['drug_code'])}

        def collect(value):
            if isinstance(value, dict):
                code = value.get('drug_code')
                if isinstance(code, str) and code in directory.products:
                    selected[code] = orderable(directory.products[code])
                for child in value.values():
                    collect(child)
            elif isinstance(value, list):
                for child in value:
                    collect(child)
        collect(observation)
        observation.update(formulary=list(selected.values()), formulary_search={
            'orderable_products': len(directory.products), 'version': directory.descriptor['version'],
            'instruction': 'Search the shared hospital formulary by English drug name, product code or name plus strength/route. '
                           'Use a returned drug_code, route and units when prescribing. Official terms without a selectable '
                           'product are vocabulary only. Choose treatment, dose and schedule from the encounter.'})
        while True:
            reply = self.role_response(role, observation, phase=phase, family=family)
            if reply.get('action') != 'search_formulary':
                return reply
            pages = [directory.search(q, reply.get('offset', 0)) for q in reply['queries']]
            if frequency_codes is not None:
                pages = [{**page, 'products': [orderable(p) for p in page['products']]} for page in pages]
            observation['formulary_results'] = pages
            for page in pages:
                for product in page['products']:
                    selected[product['drug_code']] = product
            # Previously viewed products stay available across successive searches in this decision.
            observation['formulary'] = list(selected.values())
            self.event('formulary_searched', role=role, phase=phase, queries=reply['queries'],
                       offset=reply.get('offset', 0), returned=[[p['drug_code'] for p in page['products']] for page in pages])

