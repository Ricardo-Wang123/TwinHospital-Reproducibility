    def consult_prior_evidence(self, clinical_stop, routes, pending_review):
        remaining = self.history_queries_remaining('consultation')
        sections = [key for key, info in self.history['initial_view']['sections'].items()
                    if info.get('total_count') and (
                        key == 'diagnoses' or key.startswith(('historical_', 'encounter_')))]
        if not sections or remaining <= 0:
            return False
        checks = []
        self.activity('doctor', 'diagnostic')
        plan = self.respond('doctor', {'action': 'locate_prior_evidence', **self.clinical_context(),
            'reason_for_return': str(clinical_stop), 'pending_prescription_review': pending_review,
            'available_sections': sections, 'maximum_queries': min(3, remaining)}, phase='ed_history_reassessment')
        for request in plan['queries']:
            if request['section'] in sections:
                self.read_history({**request, 'offset': 0, 'limit': 4}, 'consultation')
                feedback = deepcopy(self.history['last_query_feedback'])
            else:
                feedback = {'status': 'section_unavailable_for_historical_lookup', 'available_sections': sections,
                            'accepted_into_context': False, 'native_read_attempted': False}
            checks.append({'clinical_question': plan['question'], 'query': deepcopy(request),
                           'readback': feedback})
        work = {'work_id': f"{self.prefix}:clinical-work:{len(routes)+1}", 'requested_by': 'doctor',
                'owner': 'hospital_history', 'return_to': 'doctor', 'status': 'chart_queries_completed',
                'request': {'action': 'consult_prior_evidence', 'checks': checks},
                'clinical_decision_changed_by_runtime': False}
        routes.append(work)
        self.result['artifacts']['ed_prior_treatment_review'] = deepcopy(work['request'])
        self.pending_clinical_work = {'work_id': work['work_id'], 'owner': 'doctor',
            'task': 'Reassess the unresolved prescribing decision using the chart query results.',
            'service_request': deepcopy(work['request']), 'return_from': 'hospital_history',
            'pending_prescription_review': deepcopy(pending_review)}
        self.event('clinical_work_routed', work=deepcopy(work), same_encounter=True)
        return True

    def resolve_pending_care(self, clinical_stop):
        artifacts = self.result['artifacts']
        termination = artifacts.get('prescription_termination', {})
        initial_no_rx = (not self.order_id and artifacts.get('prescription_eligibility', {}).get('decision')
                         in {'no_prescription_issued', 'prescribing_pending'})
        review_pending = termination.get('status') in {
            'physician_deferred_after_review', 'physician_withheld_after_review',
            'physician_retained_rejected_prescription', 'physician_retained_unapproved_prescription'}
        if (not self.scenario_conditions or not self.runner.close_prescription_loop
                or (self.prescription_business_state or {}).get('status') == 'signed'
                or not (initial_no_rx or review_pending)):
            return False
        routes = self.result['artifacts'].setdefault('clinical_work_routes', [])
        remaining_routes = self.work_limit('care_work_routes', len(routes)) - len(routes)
        pending_review = deepcopy(termination) if review_pending else None
        if (self.emergency and 'ed_prior_treatment_review' not in artifacts
                and self.consult_prior_evidence(clinical_stop, routes, pending_review)):
            return True
        evidence = digest([self.history,self.physician_transcript(),self.current_measurement_panel,
                           artifacts.get('in_hospital_services',[]), pending_review])
        self.activity('doctor','diagnostic')
        request = self.respond('doctor', {'action':'resolve_pending_care', **self.clinical_context(),
            'reason_for_return':str(clinical_stop),
            'pending_prescription_review':pending_review,
            'remaining_interactions':self.work_limit('consultation_turns', self.consultation_interactions_used)-self.consultation_interactions_used,
            'remaining_history_queries':self.history_queries_remaining('consultation'),
            'remaining_reconciliation_requests':self.work_limit('in_hospital_reconciliation_requests', self.in_hospital_reconciliation_requests)-self.in_hospital_reconciliation_requests,
            'remaining_care_work_routes':remaining_routes,
            'formulary':deepcopy(self.case['formulary']),
            'available_services':{'patient_questions':True,'existing_chart_queries':True,
                                  'pharmacist_reconciliation':True,'new_investigation_results':False,
                                  **({'recorded_ed_workup_review': True,
                                      'await_collected_specimens': 'ed_lab_reports' in self.case['his_initial']
                                        and 'ed_labs_ed_reassessment' not in self.history} if self.emergency else {})}},
            phase='clinical_work_routing')
        action = request['action']
        record = {'work_id':f'{self.prefix}:clinical-work:{len(routes)+1}',
            'requested_by':'doctor','return_to':'doctor','request':deepcopy(request),
            'evidence_hash':evidence,'status':'requested','clinical_decision_changed_by_runtime':False}
        routes.append(record)
        new_reports = False
        if (self.emergency and (not self.prescribing_required or self.ed_prescribing_phase == 'reassessment')
                and 'ed_lab_reports' in self.case['his_initial'] and (action == 'request_investigation' or request.get('decision_scope') == 'pending_assessment'
                 or (action == 'resume_assessment' and request.get('await_charted_results') is True))):
            new_reports = self.release_ed_labs('ed_reassessment')
        needs_results = self.emergency and (action == 'request_investigation' or
            (action == 'confirm_no_prescription' and request['decision_scope'] == 'pending_assessment'))
        if needs_results and 'ed_investigation_review' in self.history and not new_reports:
            receipt = {'requested': deepcopy(request.get('issues') or request.get('outstanding_checks')),
                       'status': 'no_new_results_released_since_previous_request',
                       'documented_ed_workup': self.history.get('ed_workup', {}),
                       'recorded_test_directory': self.history.get('ed_diagnostic_directory', {}),
                       'interpretation': 'A repeat request does not produce a new examination. Review the existing '
                           'physical findings, collateral history, and named reports for each active problem. '
                           'State specifically which requested findings are still undocumented.',
                       'queryable_chart_sections': [*self.history['initial_view']['sections'],
                           *(['ed_diagnostic_reports', 'ed_reassessment_reports'] if 'ed_diagnostic_directory' in self.history else [])],
                       'prior_chart_can_still_be_queried': True}
            self.event('ed_investigation_request_returned', work_id=record['work_id'], chart_response=receipt)
            self.activity('doctor', 'diagnostic')
            request = self.respond('doctor', {'action': 'review_source_gap', **self.clinical_context(),
                'chart_response': receipt}, phase='ed_source_gap_review')
            action = request['action']
            record.update(investigation_request=record['request'], chart_response=receipt, request=deepcopy(request))
            if action == 'await_source_evidence':
                record.update(owner='doctor', status='physician_awaiting_unrecorded_findings')
                artifacts['unavailable_ed_evidence'] = deepcopy(request)
                self.event('clinical_work_not_completed', work=deepcopy(record))
                return False
            needs_results = False
        if needs_results:
            observations = [row for row in self.ed_chart_rows('current_observations')
                            if row['record'].get('available_at') == 'physician_consultation']
            status = {'requested': deepcopy(request.get('issues') or request.get('outstanding_checks')),
                      'recorded_observations': observations[:MAX_PAGE_RECORDS],
                      'total_recorded_observations': len(observations),
                      'further_results_section': 'current_observations',
                      'interpretation': 'These are charted measurements. Review the ED workup and any released lab panels in hospital_history. '
                          'An investigation order alone supplies no finding. If needed evidence is absent, '
                          'document which decision it prevents and decide how the patient will leave ED care.'}
            if 'ed_diagnostic_directory' in self.history:
                status.update(further_results_section='ed_diagnostic_reports',
                              available_tests=self.history['ed_diagnostic_directory']['available_tests'],
                              interpretation='Query recorded ED results by test name or specimen. Report times are source timestamps.')
            self.history['ed_investigation_review'] = status
            artifacts['ed_investigation_review'] = deepcopy(status)
            record.update(owner='doctor', status='existing_investigations_reviewed',
                          chart_response_hash=digest(status))
            self.complete_focused_assessment(record)
        elif action in {'confirm_no_prescription','request_investigation'}:
            record.update(owner='doctor' if action=='confirm_no_prescription' else 'diagnostic_service',
                status='physician_confirmed_no_prescription' if action=='confirm_no_prescription' else 'required_service_not_implemented')
            self.event('clinical_work_not_completed', work=deepcopy(record))
            return False
        elif action=='resume_assessment':
            key=('doctor',evidence)
            if key in self.clinical_work_evidence:
                self.event('repeated_care_request', role='doctor', work_id=record['work_id'],
                           evidence_hash=evidence, request_hash=digest(request))
            self.clinical_work_evidence.add(key)
            record.update(owner='doctor',status='awaiting_physician_assessment')
            self.complete_focused_assessment(record)
        elif action=='ask':
            self.activity('doctor','diagnostic')
            self.ask_patient('doctor',request['question'],'consultation')
            self.consultation_interactions_used += 1
            record.update(owner='patient',status='patient_answer_observed')
        elif action=='read_history':
            self.read_history(request,'consultation')
            record.update(owner='hospital_history',status='chart_response_observed')
        elif action=='request_medication_reconciliation':
            review={'decision':'defer','source':'physician_requested_medication_information',
                    'reason':request['reason'],'issues':deepcopy(request['issues'])}
            if not self.reconcile_in_hospital(review,{'items':[]}):
                record.update(owner='pharmacist',status='reconciliation_not_completed')
                return False
            record.update(owner='pharmacist',status='reconciliation_observed')
        else:
            raise WorkflowFailure('Unsupported physician care-work action')
        self.pending_clinical_work = {'work_id':record['work_id'],'owner':'doctor',
            'task':request.get('work') or request.get('reason'),
            'service_request':deepcopy(request),'return_from':record['owner'],
            'pending_prescription_review':pending_review}
        self.event('clinical_work_routed',work=deepcopy(record),same_encounter=True)
        return True

    def complete_focused_assessment(self, record):
        while True:
            self.activity('doctor', 'diagnostic')
            response = self.respond('doctor', {
                'action': 'assess_pending_care', **self.clinical_context(),
                'assigned_work': deepcopy(record['request']),
                'pending_prescription_review': deepcopy(self.result['artifacts'].get('prescription_termination')),
                'remaining_interactions': self.work_limit('consultation_turns', self.consultation_interactions_used)-self.consultation_interactions_used,
                'remaining_history_queries': self.history_queries_remaining('consultation')},
                phase='focused_physician_assessment')
            if response['action'] == 'ask':
                self.ask_patient('doctor', response['question'], 'consultation')
                self.consultation_interactions_used += 1
            elif response['action'] == 'read_history':
                self.read_history(response, 'consultation')
            else:
                assessment = {'work_id': record['work_id'], 'owner': 'doctor',
                    'response': deepcopy(response), 'response_hash': digest(response),
                    'source': 'actual_physician_assessment_not_new_measurement'}
                self.result['artifacts'].setdefault('focused_assessments', []).append(assessment)
                record.update(status='assessment_completed', assessment_hash=digest(assessment))
                self.event('focused_assessment_completed', work_id=record['work_id'],
                           response_hash=digest(response), unresolved_issues=len(response['unresolved_issues']))
                return

    def document_clinical_disposition(self, condition, clinical_stop):
        """Write the actual non-prescribing decision without completing/charging the chain."""
        artifacts = self.result["artifacts"]
        trigger = next((call["phase"] for call in reversed(self.calls)), "clinical_decision")
        self.clinical_disposition = {
            "status": "incomplete_clinical_decision", "trigger_phase": trigger,
            "reason": str(clinical_stop), "prescription_eligibility": deepcopy(artifacts.get("prescription_eligibility")),
            "prescription_termination": deepcopy(artifacts.get("prescription_termination")),
            "unresolved_adjudication": deepcopy(artifacts.get("unresolved_prescription_adjudication")),
            "original_candidate": deepcopy(artifacts.get("original_prescription")),
            "original_review": deepcopy(artifacts.get("original_prescription_review")),
            "approved_prescription_available": False, "drug_settlement_attempted": False,
            "clinical_appropriateness": "not_assessed_outside_programmatic_scope"}
        artifacts["clinical_disposition"] = deepcopy(self.clinical_disposition)
        if self.emergency and self.runner.close_prescription_loop:
            self.event('ed_documentation_pending', reason='no_signed_medication_order',
                       disposition_finalized=False, note_attested=False)
            return
        if self.emergency:
            # Departure and the absence of an approved medication order are separate outcomes.
            self.decide_ed_disposition(self.physician_transcript(), self.consultation_record, {'items': []})
            self.clinical_disposition['ed_disposition'] = deepcopy(artifacts['ed_disposition'])
            artifacts['clinical_disposition'] = deepcopy(self.clinical_disposition)
        elif self.runner.close_prescription_loop:
            # A bare defer is not a patient-facing outcome. Ask for the next
            # clinical action, preserving unavailable evidence and all reviews.
            # This is one distinct planning action, not another attempt to obtain
            # an approval or to generate a convenient laboratory result.
            outcome = {"status": "pending", "planned_actions_executed": False,
                "drug_order_signed": False, "drug_payment_completed": False}
            artifacts['final_care_plan_outcome'] = outcome
            try:
                self.activity('doctor', 'prescription_revision')
                plan = self.respond('doctor', {'action': 'finalize_care_plan',
                    **self.clinical_context(), 'clinical_disposition': deepcopy(self.clinical_disposition),
                    'scope': 'This remains unfinished within the virtual hospital. State the exact remaining clinical information or unimplemented service needed here, and the responsible in-hospital role. Staff, drugs and equipment are nonbinding resources. Do not refer outside, claim that planned tests occurred, or count this plan/locked note as a completed visit. Do not approve the unapproved order or invent a measurement.'},
                    phase='final_care_plan')
                artifacts['final_care_plan'] = deepcopy(plan)
                self.clinical_disposition['final_care_plan'] = deepcopy(plan)
                artifacts['clinical_disposition'] = deepcopy(self.clinical_disposition)
                outcome.update(status='recorded', response_hash=digest(plan),
                    persistence='runtime_journal_then_attested_note', native_referral_or_test_order_created=False)
            except Exception as exc:
                outcome.update(status=('stopped_budget' if type(exc).__name__ == 'BudgetExceeded' else
                    'stopped_provider' if type(exc).__name__ == 'ProviderUnavailable' else 'failed'),
                    error_type=type(exc).__name__, reason=str(exc)[:600])
                if type(exc).__name__ in {'BudgetExceeded','ProviderUnavailable'}:
                    raise
            finally:
                self.event('final_care_plan_recorded', outcome=deepcopy(outcome))
        self.result["three_task_eligible"] = False
        self.result["documentation_input_eligibility"] = "documentation_only_actual_clinical_disposition"
        source = {"transcript": self.physician_transcript(), "handoff": deepcopy(self.handoff),
            "consultation": deepcopy(self.consultation_record), "hospital_history": deepcopy(self.history),
            "current_encounter_measurements": deepcopy(self.current_measurement_panel),
            "observed_business_state": {"prescription": deepcopy(self.prescription_business_state)},
            "approved_prescription": {"items": []}, "clinical_disposition": deepcopy(self.clinical_disposition)}
        self.result["stage_inputs"]["documentation"] = source
        outcome = {"status": "not_started", "input_hash": digest(source),
            "qualifies_complete_three_task_chain": False, "drug_settlement_attempted": False}
        artifacts["disposition_documentation_outcome"] = outcome
        try:
            self.documentation(condition, source["transcript"], source["consultation"], source["approved_prescription"])
            outcome.update(status="attested", note_hash=digest(artifacts["attested_note"]),
                clinical_quality="not_assessed_outside_programmatic_scope")
        except Exception as exc:
            outcome.update(status=('stopped_budget' if type(exc).__name__ == 'BudgetExceeded' else
                'stopped_provider' if type(exc).__name__ == 'ProviderUnavailable' else 'failed'),
                error_type=type(exc).__name__, failure_reason=str(exc)[:1000])
            if type(exc).__name__ in {'BudgetExceeded','ProviderUnavailable'}:
                raise
        finally:
            self.event("clinical_disposition_documented", status=outcome["status"],
                source_hash=digest(source), outcome_hash=digest(outcome),
                qualifies_complete_three_task_chain=False, drug_settlement_attempted=False)

    def documentation(self, condition, transcript, consultation, prescription):
        self.activity_stage = 'documentation'
        transcript = deepcopy(transcript)
        self.verify_physician_transcript(transcript)
        sequences = [x.get("sequence") for x in transcript]
        if any(type(x) is not int for x in sequences) or sequences != sorted(set(sequences)):
            raise WorkflowFailure("transcript sequences must be unique and increasing")
        if not transcript and not (self.handoff or consultation):
            raise WorkflowFailure("documentation requires a visible handoff, consultation or dialogue")
        note_id = self.prefix + ":note"
        version = self.note_state["version"] if self.note_state else 0
        content = deepcopy(self.note_state["content"]) if self.note_state else None
        versions = self.result["artifacts"].setdefault("note_versions", [])
        manual = condition.workflow == "manual_documentation"
        brief = None
        addendum = None
        if condition.workflow == 'brief_to_note':
            self.activity('doctor', 'brief_documentation')
            brief = self.respond('doctor', {'action': 'write_brief', 'transcript': deepcopy(transcript),
                'allowed_source_scope': {'source_sequences': sequences},
                'hospital_history': deepcopy(self.history), 'handoff': deepcopy(self.handoff),
                'current_encounter_measurements': deepcopy(self.current_measurement_panel),
                'consultation': deepcopy(consultation), 'approved_prescription': deepcopy(prescription),
                **({'ed_disposition': deepcopy(self.result['artifacts'].get('ed_disposition'))} if self.emergency else {}),
                'observed_business_state': {'prescription': deepcopy(self.prescription_business_state)}},
                phase='documentation_brief')['content']
            self.result['artifacts']['clinical_brief'] = deepcopy(brief)
        elif condition.workflow == 'postvisit':
            addendum = self.respond('doctor', {'action': 'dictate_addendum',
                'allowed_source_scope': {'source_sequences': sequences},
                'transcript': deepcopy(transcript), 'hospital_history': deepcopy(self.history),
                'current_encounter_measurements': deepcopy(self.current_measurement_panel),
                'consultation': deepcopy(consultation), 'approved_prescription': deepcopy(prescription),
                **({'ed_disposition': deepcopy(self.result['artifacts'].get('ed_disposition'))} if self.emergency else {}),
                'observed_business_state': {'prescription': deepcopy(self.prescription_business_state)}},
                phase='documentation_addendum')['content']
            if addendum['text'].strip():
                self.activity('doctor', 'note_supplementation')
            self.result['artifacts']['clinical_addendum'] = deepcopy(addendum)
        if self.scenario_conditions is not None:
            self.result['artifacts']['documentation_source_policy'] = {
                'version': scenario_design.DOCUMENTATION_SOURCE_VERSION, 'workflow': condition.workflow,
                'transcription': 'assumed_accurate_text',
                'physician_summary': brief is not None,
                'physician_addendum': addendum is not None,
                'full_dialogue_to_ai': not manual and brief is None}
        stop = len(transcript)
        prefix = transcript
        visible_history = deepcopy(self.history)
        source = {"transcript": prefix, "hospital_history": visible_history,
                  "handoff": deepcopy(self.handoff),
                  "current_encounter_measurements": deepcopy(self.current_measurement_panel),
                  "is_final_prefix": True,
                  "allowed_source_scope": {"source_sequences": [x["sequence"] for x in prefix],
                      "consultation_and_signed_prescription_available": bool(consultation and self.prescription_business_state),
                      "consultation_available": bool(consultation),
                      "signed_prescription_available": bool(self.prescription_business_state),
                      "review_standard": "final_documentation",
                      "future_information_required": False},
                  "observed_business_state": {"prescription": deepcopy(self.prescription_business_state)},
                  "clinical_disposition": deepcopy(self.clinical_disposition),
                  "clinical_addendum": deepcopy(addendum),
                  "consultation": consultation,
                  "approved_prescription": prescription}
        if self.emergency:
            source['ed_disposition'] = deepcopy(self.result['artifacts'].get('ed_disposition'))
            if self.ed_prescription_signed and source['ed_disposition']:
                self.result['ed_note_reconciliation_policy'] = emergency.NOTE_RECONCILIATION_POLICY
                source['ed_note_final_state'] = {
                    'order_codes': sorted({item['drug_code'] for item in prescription['items']}),
                    'disposition': source['ed_disposition']['code'],
                }
        role = "doctor" if manual else "scribe"
        if manual:
            self.activity(role, "documentation")
        writing_source = deepcopy(source)
        if not manual:
            writing_source.update(consultation=None, handoff=None)
            writing_source['allowed_source_scope'].update(
                consultation_available=False, consultation_and_signed_prescription_available=False)
            if self.post_signature_review:
                chart = visible_history.get('initial_view', {})
                writing_source['hospital_history'] = {'demographics': chart.get('demographics', {}),
                    'allergy_record': chart.get('allergy_record', {}),
                    'ed_allergy_updates': deepcopy(visible_history.get('ed_allergy_updates', []))}
                writing_source['documentation_common_fields'] = 'ed_note_clinical_data_v1'
        if brief is not None:
            writing_source.update(transcript=[], clinical_brief=deepcopy(brief),
                                  input_mode='physician_dictation_and_clinical_records')
            writing_source['allowed_source_scope'].update(
                source_sequences=[], full_transcript_available=False)
        elif addendum is not None:
            writing_source.update(input_mode='encounter_transcript_and_physician_addendum')
            writing_source['allowed_source_scope']['full_transcript_available'] = True
        draft = self.respond(role, {"action": "document", **writing_source, "previous_draft": content,
                                  "is_final_prefix": True}, phase=f"documentation_draft_{stop}",
                              family=condition.model_family)
        content = draft.get("content")
        if not isinstance(content, dict) or not isinstance(content.get("text"), str):
            raise WorkflowFailure("note draft requires independent content.text")
        def save(new_content, author, reason, visible_dialogue):
            if self.emergency and self.history.get('ed_allergy_updates'):
                opening = next((row for table in self.ed_review.get('presentation', {}).get('results', [])
                                if table['section'] == 'allergy_record' for row in emergency.table_records(table)),
                               self.history['initial_view'].get('allergy_record'))
                new_content['ed_allergy_history'] = {
                    'opening': deepcopy(opening),
                    'updates':deepcopy(self.history['ed_allergy_updates'])}
            elif self.emergency:
                new_content.pop('ed_allergy_history', None)
            if self.result['artifacts'].get('ed_signed_order_history'):
                new_content['ed_signed_order_history'] = deepcopy(self.result['artifacts']['ed_signed_order_history'])
            if self.emergency and 'ed_disposition' in self.result['artifacts']:
                new_content['ed_disposition'] = deepcopy(self.result['artifacts']['ed_disposition'])
            nonlocal version
            op = "note.save" if version == 0 else "note.revise"
            state = self.perform(op, {"note_id": note_id, "content": new_content,
                "expected_version": version, "parent_version": version or None}, author)
            if state.get("version") != version+1:
                raise WorkflowFailure("note version read-back mismatch")
            version += 1
            versions.append({"version": version, "content": deepcopy(new_content), "author_role": author,
                             "source_sequences": [x["sequence"] for x in visible_dialogue], "reason": reason})
        save(content, role, "initial_draft", writing_source['transcript'])
        if not manual and self.post_signature_review:
            versions[-1]['origin'] = 'AI generated for treating physician review'
        accepted = False
        for review_index in self.work_steps('max_note_revisions', scope=stop):
            self.activity("doctor", "note_review")
            final_state = source.get('ed_note_final_state')
            checked_plan = {}
            if final_state:
                checked_plan = {'ed_plan_check': emergency.note_order_disposition_check(
                    content['text'], final_state['order_codes'], final_state['disposition'])}
            review = self.respond("doctor", {"action": "finalize_note", **source,
                "content": content, "version": version, **checked_plan,
                "remaining_note_revisions": self.work_limit('max_note_revisions', review_index, scope=stop) - review_index,
                "current_note_identity": {"version": version, "content_hash": digest(content)},
                "review_context_policy": deepcopy(NOTE_FINALIZATION_POLICY),
                "previous_review_index": [{k: deepcopy(r[k]) for k in
                    ("reviewed_version", "content_hash", "source_sequences", "is_final_prefix")}
                    for r in self.note_review_history]}, phase=f"note_review_{stop}_{review_index}")
            review_record = {"reviewed_version": version, "content_hash": digest(content),
                "source_sequences": [x["sequence"] for x in prefix], "is_final_prefix": True,
                "decision": review.get("decision"), "reason": review.get("reason"),
                'finalized': review.get('finalized')}
            self.note_review_history.append(deepcopy(review_record))
            self.result["artifacts"].setdefault("note_reviews", []).append({
                **review_record, "response": deepcopy(review), "revision_saved": False})
            if review.get("decision") == "accept":
                accepted = True
                break
            if review.get('decision') in {'reject', 'revise'}:
                self.event('note_returned_for_revision', role='doctor', version=version,
                           content_hash=digest(content), review_hash=digest(review))
            if review.get('decision') == 'reject' and self.continuous:
                self.activity('doctor', 'note_rework')
                revised = self.respond('doctor', {'action': 'document', **source,
                    'previous_draft': deepcopy(content), 'revision_request': deepcopy(review)},
                    phase=f'note_rewrite_{stop}_{review_index}')
                content = revised['content']
                save(content, 'doctor', 'physician_rewrite_after_rejection', transcript)
                continue
            if review.get("decision") != "revise" or not isinstance(review.get("content"), dict):
                raise WorkflowFailure("physician rejected note or returned an invalid review")
            content = review["content"]
            if not isinstance(content.get("text"), str):
                raise WorkflowFailure("note revision requires text")
            if (not self.continuous and review_index >= self.runner.limits["max_note_revisions"]
                    and review.get('finalized') is not True):
                # Keep the proposed text in the response audit, but do not
                # create a business version that cannot receive its review.
                break
            self.activity("doctor", "note_rework")
            save(content, "doctor", "physician_revision", transcript)
            self.result["artifacts"]["note_reviews"][-1]["revision_saved"] = True
            if review.get('finalized') is True:
                accepted = True
                self.event('physician_corrected_note_finalized', version=version,
                           content_hash=digest(content), source='explicit_physician_finalization')
                break
        if not accepted:
            raise WorkflowFailure("note review limit exhausted without acceptance")
        self.note_state = {"version": version, "content": deepcopy(content)}
        self.activity("doctor", "attestation")
        state = self.perform("note.attest", {"note_id": note_id, "version": version}, "doctor")
        if state.get("status") != "locked":
            raise WorkflowFailure("note attestation not confirmed")
        self.result["artifacts"]["attested_note"] = {"note_id": note_id, "version": version,
            "content": deepcopy(content), "status": "locked"}

    def decide_ed_disposition(self, transcript, consultation, approved):
        self.activity_stage = 'documentation'
        if 'ed_closing_reports' in self.case['his_initial'] and 'closing' not in self.ed_review:
            self.open_ed_diagnostic_directory('closing')
            if not self.ips_on_demand:
                sections = ('ed_closing_reports', 'ed_closing_workup') if self.single_prescription else ('ed_closing_reports',)
                self.review_ed_chart('closing', sections)
        if 'reassessment' in self.ed_review:
            self.history['ed_reassessment'] = deepcopy(self.ed_review['reassessment'])
        self.activity('doctor', 'diagnostic')
        decision = self.respond('doctor', {'action': 'decide_ed_disposition',
            'transcript': transcript, 'consultation': consultation, 'hospital_history': self.history,
            'current_encounter_measurements': self.current_measurement_panel,
            'approved_prescription': approved}, phase='ed_disposition')
        self.result['artifacts']['ed_disposition'] = {'code': decision['code'], 'reason': decision['reason']}

    def close_ed_encounter(self):
        evidence = emergency.verified_closure({**self.result, 'events': self.events, 'calls': self.calls})
        self.result['artifacts']['ed_closure'] = evidence
        self.event('ed_encounter_closed', document_id=evidence['document_id'], order_id=evidence['order_id'],
                   disposition=evidence['disposition'])

    def settle(self):
        bill = self.perform("payment.prepare", {"order_id": self.order_id}, "cashier")
        if not all(key in bill for key in ("bill_id", "amount", "currency")):
            raise WorkflowFailure("pre-settlement did not return an actual bill")
        paid = self.perform("payment.commit", {"bill_id": bill["bill_id"], "amount": bill["amount"],
            "currency": bill["currency"], "channel": "CASH", "transaction_id": self.prefix + ":payment"}, "cashier")
        if paid.get("status") != "paid":
            raise WorkflowFailure("simulated settlement not confirmed")
        self.result["artifacts"]["settlement"] = {"bill": bill, "payment": paid, "simulated": True}

    def execute(self, function, *, conditions, complete=True):
        from .continuation import EncounterDeferred
        start = time.monotonic()
        self.result["conditions"] = conditions
        self.result["evaluation_unit"] = "complete_encounter" if complete else "fixed_input_task"
        self.event("run_started", conditions=conditions)
        try:
            function()
            self.result["status"] = "completed"
            self.result["workflow_complete"] = complete
            operations = [e for e in self.events if e["event"] == "business_operation"]
            native = [e for e in operations if e["operation"] == "registration.create" or
                      e["operation"].startswith(("order.", "note.", "payment."))]
            self.result["native_complete"] = bool(complete and native and all(
                e["response"].get("native_effect") is True for e in native))
            self.event("run_completed", native_complete=self.result["native_complete"])
        except KeyboardInterrupt:
            self.result.update(status="failed", workflow_complete=False, error_type="KeyboardInterrupt",
                               failure_reason="Operator interrupted workflow execution")
            self.event("run_interrupted", error_type="KeyboardInterrupt")
            raise
        except Exception as exc:
            # Account/budget stops do not establish a clinical decision.
            status = ('waiting_retry' if isinstance(exc, EncounterDeferred) else
                      "stopped_budget" if type(exc).__name__ == "BudgetExceeded" else
                      "stopped_provider" if type(exc).__name__ == "ProviderUnavailable" else
                      "incomplete_clinical_decision" if isinstance(exc, (ClinicalDecisionIncomplete, EDChecksUnresolved)) else "failed")
            self.result.update(status=status, workflow_complete=False,
                               error_type=type(exc).__name__, failure_reason=str(exc)[:1000])
            if isinstance(exc, EncounterDeferred):
                self.result['provider_interruption'] = deepcopy(exc.issue)
                self.event('provider_retry_queued', issue=deepcopy(exc.issue), same_encounter=True,
                           verified_complete=False, queue_position='tail')
            else:
                self.event("run_failed", error_type=type(exc).__name__, reason=str(exc)[:1000])
        finally:
            followthrough=self.result['artifacts'].get('prescription_followthrough')
            if followthrough and followthrough.get('status')=='running':
                followthrough.update(status='not_closed',runtime_status=self.result['status'],
                    drug_payment_completed=False)
            self.result.update(ended_at=_utc(), wall_seconds=time.monotonic()-start,
                               call_count=len(self.calls), activity_count=len(self.activities))
            if self.runner.continuation:
                self.result['continuation'] = {key: deepcopy(self.runner.continuation.data[key])
                    for key in ('policy', 'segments', 'interruptions', 'started_at')}
                self.result['wall_seconds'] = time.monotonic() - self.clock_origin
                issues = self.result.setdefault('workflow_issues', [])
                for interruption in self.runner.continuation.data['interruptions']:
                    issue_id = digest([self.context['run_id'], 'provider', interruption['number']])[:24]
                    existing = next((i for i in issues if i['issue_id'] == issue_id), None)
                    if existing is None:
                        existing = {'issue_id': issue_id, **deepcopy(self.context),
                            'event_class':'model_execution', 'code':'provider_interruption', 'owner':'dispatcher',
                            'review_status':'not_reviewed', 'clinical_validity_inferred':False}
                        issues.append(existing)
                    existing.update({k: deepcopy(interruption[k]) for k in
                        ('status', 'reason_code', 'request_id', 'occurred_at', 'resolved_at', 'entry_position')})
                    recovery = interruption.get('recovery_request_id')
                    if recovery:
                        recovered_call = next((call for call in self.calls if call.get('request_id') == recovery), None)
                        if recovered_call:
                            observation = next((event for event in self.events if event['event'] == 'role_call'
                                                and event['call_sequence'] == recovered_call['sequence']), None)
                            if observation:
                                existing.update(resolution_event_sequence=observation['sequence'],
                                                resolution_execution_segment=observation['execution_segment'])
            self.result["history_query_counts"] = deepcopy(self.history_query_counts)
            if self.history is not None:
                self.result["history_coverage"] = {
                    "status": "bounded_selected_records_not_a_complete_chart_read",
                    "queried_page_count": len(self.history["queried_pages"]),
                    "retained_record_refs": sorted({record["record_ref"]
                        for entry in self.history["queried_pages"] for record in entry["page"]["records"]}),
                    "budget_exhausted_phases": [phase for phase, used in self.history_query_counts.items()
                                               if not self.continuous and used >= self.runner.limits['history_queries_per_phase']],
                    "unread_page_cursors": [{"section": entry["page"]["section"],
                        "next_offset": entry["page"]["next_offset"]} for entry in self.history["queried_pages"]
                        if entry["page"].get("next_offset") is not None],
                    "unknown_is_not_negative": True}
            self.result["artifacts"]["transcript"] = deepcopy(self.transcript)
            self.result["activities"] = deepcopy(self.activities)
            self.result["events"] = deepcopy(self.events)
            self.result["calls"] = deepcopy(self.calls)
            from .workflow_events import summarize
            self.result['workflow_event_summary'] = summarize(self.result.get('workflow_issues', []), self.events)
            if self.scenario_conditions:
                self.result['measurements'] = scenario_design.measurements(self.result)
            self.write()
        return deepcopy(self.result)

    def write(self):
        if self.runner.output_dir is None:
            return
        directory = self.directory
        def write(name, value):
            path = directory / name
            path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
            os.chmod(path, 0o600)
        write("run.json", self.result)
        # Appendix trace excludes dialogue, facts, native identifiers and raw backend bodies.
        summary = {k: self.result[k] for k in ("schema_version", "case_id", "group", "data_kind", "split",
                   "config_id", "conditions", "status", "evaluation_unit", "native_complete", "call_count",
                   "wall_seconds", "timing_source")}
        summary["clinical_quality"] = self.result["clinical_quality"]
        summary['workflow_event_summary'] = deepcopy(self.result['workflow_event_summary'])
        summary['workflow_issues'] = [{k: v for k, v in issue.items() if k in {
            'issue_id', 'event_class', 'code', 'owner', 'status', 'review_status',
            'source_event_sequence', 'source_execution_segment', 'resolution_event_sequence',
            'resolution_execution_segment', 'workflow_endpoint_observed'}}
            for issue in self.result.get('workflow_issues', [])]
        if self.scenario_conditions:
            summary['scenario_design'] = self.result['scenario_design']
            summary['measurements'] = deepcopy(self.result['measurements'])
        summary["note_review_policy"] = self.result["note_review_policy"]
        summary["current_measurement_policy"] = self.result["current_measurement_policy"]
        summary["response_contract_policy"] = self.result["response_contract_policy"]
        summary["clinical_disposition_policy"] = self.result["clinical_disposition_policy"]
        summary["prescription_followthrough_policy"] = self.result["prescription_followthrough_policy"]
        if 'prescription_followthrough' in self.result['artifacts']:
            summary['prescription_followthrough'] = {k:v for k,v in
                self.result['artifacts']['prescription_followthrough'].items()
                if k not in {'source_state'}}
        if "prescription_eligibility" in self.result["artifacts"]:
            summary["prescription_eligibility"] = {k: v for k, v in
                self.result["artifacts"]["prescription_eligibility"].items() if k != "stated_reason"}
        summary["history_query_counts"] = self.result.get("history_query_counts", {})
        summary["history_access_policy"] = self.result.get("history_access_policy")
        summary["history_coverage"] = self.result.get("history_coverage")
        if self.clinical_disposition is not None:
            summary["clinical_disposition"] = {"status": self.clinical_disposition["status"],
                "trigger_phase": self.clinical_disposition["trigger_phase"],
                "clinical_appropriateness": "not_assessed_outside_programmatic_scope",
                "three_task_eligible": False, "drug_settlement_attempted": False}
            summary["disposition_documentation_outcome"] = {k:v for k,v in
                self.result["artifacts"].get("disposition_documentation_outcome", {}).items() if k != "failure_reason"}
        summary["events"] = []
        for event in self.events:
            item = {k: event[k] for k in ("sequence", "event", "operation", "role", "phase", "status",
                    "model_family", "version", "error_type", "payload_hash", "response_hash",
                    "lookup_number", "section", "returned_count", "accepted_into_context", "wall_seconds",
                    "retained_context_bytes", "remaining_visible_bytes", "raw_page_bytes", "projected_page_bytes",
                    "raw_page_hash", "projected_page_hash", "projection_version", "already_visible_record_refs",
                    "new_record_refs", "next_offset", "matching_count", "result_status", "query_hash", "returned_refs", "native_write_attempted") if k in event}
            if event["event"] == "business_operation":
                item.update({k: event["response"].get(k) for k in (
                    "status", "readback_verified", "native_effect", "protection_source")})
            summary["events"].append(item)
        summary["model_calls"] = [{k: call.get(k) for k in ("sequence", "role", "phase", "model_family",
                                  "model_name", "memory_policy", "request_id", "status", "wall_seconds", "usage",
                                  "response_parse",
                                  "schema_correction_attempt", "original_clinical_input_hash", "response_schema_errors")}
                                  for call in self.calls]
        summary["artifact_hashes"] = {k: digest(v) for k, v in self.result["artifacts"].items()}
        # Raw backend errors can contain identifiers or clinical text; keep them only locally.
        summary["error_type"] = self.result.get("error_type")
        summary["failure_stage"] = next((e.get("operation", e.get("phase")) for e in reversed(self.events)
                                          if e["event"] in {"business_operation", "role_call"}), None)
        if self.result["status"] == "incomplete_clinical_decision" and self.clinical_disposition is not None:
            summary["failure_stage"] = self.clinical_disposition["trigger_phase"]
        write("appendix_trace.json", summary)
