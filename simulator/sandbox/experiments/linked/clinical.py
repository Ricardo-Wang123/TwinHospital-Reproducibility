    def physician_transcript(self):
        """Conversation personally available to the physician, separate from audit."""
        return deepcopy([segment for segment in self.transcript
                         if segment.get("phase") in PHYSICIAN_DIALOGUE_PHASES])

    @staticmethod
    def verify_physician_transcript(transcript):
        if not isinstance(transcript, list) or any(not isinstance(segment, dict) or
                segment.get("phase") not in PHYSICIAN_DIALOGUE_PHASES for segment in transcript):
            raise WorkflowFailure("clinical source transcript contains dialogue outside physician visibility")

    def begin_consultation(self, *, load_measurement_panel=True):
        begun = self.perform("encounter.begin_consultation", {}, "doctor")
        if str(begun.get("encounter_id")) != str(self.context["encounter_id"]):
            raise WorkflowFailure("consultation start does not match registered encounter")
        if load_measurement_panel:
            # These are already-recorded current measurements released at the
            # consultation boundary, not new tests or inferred historical values.
            page = self.perform("history.query", {"section": "current_observations", "offset": 0,
                "limit": CURRENT_MEASUREMENT_POLICY["max_records"]}, "doctor", write=False).get("page")
            if (not isinstance(page, dict) or page.get("section") != "current_observations" or
                    not isinstance(page.get("records"), list) or json_bytes(page) > PAGE_BYTE_LIMIT):
                raise WorkflowFailure("invalid current measurement panel readback")
            panel = {"records": [], "source_section": "current_observations",
                "source_operation": "history.query", "readback_verified": True,
                "available_at": "physician_consultation", "observed_at": self.observation_time('current_measurement_panel'),
                "queried_after_sequence": self.transcript[-1]["sequence"] if self.transcript else 0,
                "time_basis": deepcopy(page.get("time_basis")),
                "unshown_is_not_absent": True, "withheld_or_oversize_returned_records": 0,
                "next_offset": page.get("next_offset"), "total_count": page.get("total_count")}
            for row in page["records"]:
                if not isinstance(row, dict) or not isinstance(row.get("record_ref"), str):
                    raise WorkflowFailure("current measurement lacks a record reference")
                if row.get("record", {}).get("available_at") != "physician_consultation":
                    panel["withheld_or_oversize_returned_records"] += 1
                    continue
                candidate = {**panel, "records": panel["records"] + [deepcopy(row)]}
                if json_bytes(candidate) > CURRENT_MEASUREMENT_POLICY["max_bytes"]:
                    panel["withheld_or_oversize_returned_records"] += 1
                    continue
                panel["records"].append(deepcopy(row))
            self.current_measurement_panel = panel
            self.result["artifacts"]["current_encounter_measurements"] = deepcopy(panel)
            self.event("current_measurement_panel_read", returned_refs=[row["record_ref"] for row in panel["records"]],
                returned_count=len(panel["records"]), source_section="current_observations",
                readback_verified=True, manual_history_query_budget_consumed=False,
                withheld_or_oversize_returned_records=panel["withheld_or_oversize_returned_records"])

    def open_consultation(self):
        self.consultation_interactions_used = 0
        if self.ed_source_review_required and not self.ips_on_demand and 'prior' not in self.ed_review:
            self.review_ed_chart('prior', emergency.PRIOR_REVIEW_SECTIONS)
        self.begin_consultation(load_measurement_panel=not self.ips_on_demand)
        self.activity('doctor', 'diagnostic')
        self.ask_patient('doctor', CONSULTATION_DIALOGUE_POLICY['opening_question'], 'consultation')
        self.event('standard_consultation_opening_completed', policy=CONSULTATION_DIALOGUE_POLICY['version'])

        condition = self.scenario_conditions['preconsult'] if self.scenario_conditions else None
        if condition is None or condition.workflow == 'direct_consultation':
            return
        followup = self.respond('doctor', {'action': 'first_intake_followup', **self.clinical_context()},
                                phase='consultation')
        physician_call = self.calls[-1]['sequence']
        self.activity('doctor', 'diagnostic')
        self.ask_patient('doctor', followup['question'], 'consultation')
        self.consultation_interactions_used = 1
        self.event('first_intake_followup_completed', physician_call=physician_call,
                   patient_call=self.calls[-1]['sequence'])
        if condition.workflow == 'report_during_consultation':
            self.read_preconsult_report('during_consultation')

    def consult(self, *, resume=False):
        if not resume:
            self.open_consultation()
        if self.emergency and 'ed_diagnostic_reports' in self.case['his_initial'] and 'ed_diagnostic_directory' not in self.history:
            self.open_ed_diagnostic_directory()
        if not resume and not self.ips_on_demand and self.emergency and 'ed_workup' in self.case['his_initial']:
            self.release_ed_workup()
        if not resume and not self.ips_on_demand and self.emergency and 'ed_lab_reports' in self.case['his_initial']:
            self.release_ed_labs('initial_prescribing')
        if (self.emergency and not self.ips_on_demand and 'ed_diagnostic_directory' in self.history
                and 'presentation' not in self.ed_review):
            if 'prior' not in self.ed_review:
                self.review_ed_chart('prior', emergency.PRIOR_REVIEW_SECTIONS)
            self.review_ed_chart('presentation', emergency.PRESENTATION_SECTIONS)
        turn = self.consultation_interactions_used
        unanswered = {}
        exhausted_history = set()
        require_assessment = False
        while self.continuous or turn <= self.runner.limits["consultation_turns"]:
            self.consultation_interactions_used=turn
            observation = {"action": "consult", **self.clinical_context(),
                "formulary": deepcopy(self.case["formulary"]),
                "diagnosis_catalogue": deepcopy(self.diagnosis_catalogue),
                "remaining_history_queries": self.history_queries_remaining("consultation"),
                "remaining_interactions": self.work_limit('consultation_turns', turn)-turn}
            if require_assessment:
                observation['require_working_assessment'] = True
            response = self.prescribing_response(observation)
            turn = self.consultation_interactions_used
            if response.get("action") == "read_history":
                key = digest({k: response.get(k) for k in ('section', 'encounter_key', 'term', 'offset', 'limit')})
                if key in exhausted_history:
                    self.event('ed_history_source_exhausted', query_hash=key, physician_call=self.calls[-1]['sequence'])
                    require_assessment = True
                    continue
                self.read_history(response, "consultation")
                query_status = (self.history.get('last_query_feedback') or {}).get('status')
                if self.post_signature_review and (query_status in {'already_visible', 'no_recorded_result'}
                        or (self.ips_on_demand and query_status == 'invalid_request')):
                    exhausted_history.add(key)
                continue
            if response.get("action") == "consultation_complete":
                if (self.longitudinal_allergy and 'consultation' not in self.allergy_disclosed and
                        self.scenario_conditions['preconsult'].workflow == 'direct_consultation'):
                    self.ask_patient('doctor', '接诊快结束了，补充自己的过敏史。', 'consultation', volunteer_allergy=True)
                    require_assessment = True
                    continue
                if self.emergency and self.scenario_conditions:
                    response = self.reassess_ed_prescription(response, initial_signing=self.prescribing_required)
                response = self.resolve_diagnosis_coding(response)
                normalized, code_changes = canonicalize(response.get('diagnoses'), self.diagnosis_catalogue)
                if code_changes:
                    original = deepcopy(response)
                    response = {**deepcopy(response), 'diagnoses': normalized}
                    mapping = {'policy': deepcopy(DIAGNOSIS_CODE_POLICY),
                        'original_response': original, 'original_response_hash': digest(original),
                        'canonical_response_hash': digest(response), 'changes': code_changes,
                        'catalogue_hash': digest(self.diagnosis_catalogue)}
                    self.result['artifacts'].setdefault('diagnosis_code_normalizations', []).append(mapping)
                    self.event('diagnosis_code_display_normalized',
                        original_response_hash=digest(original), canonical_response_hash=digest(response),
                        policy_version=DIAGNOSIS_CODE_POLICY['version'], changes=code_changes,
                        clinical_decision_changed=False)
                candidate = response.get("prescription")
                if not isinstance(candidate, dict) or not isinstance(candidate.get("items"), list):
                    raise WorkflowFailure("physician prescription must contain an explicit items list")
                if candidate["items"]:
                    validate_prescription(candidate)
                prior_services = deepcopy(self.result['artifacts'].get('in_hospital_services', []))
                prior_followups = deepcopy((self.consultation_record or {}).get('prescription_review_followups', []))
                self.consultation_record = deepcopy(response)
                if prior_services:
                    self.consultation_record['in_hospital_services'] = prior_services
                if prior_followups:
                    self.consultation_record['prescription_review_followups'] = prior_followups
                self.result["artifacts"]["consultation"] = deepcopy(response)
                self.result['artifacts'].setdefault('consultation_versions', []).append(deepcopy(response))
                diagnoses_mapped = True
                if self.diagnosis_catalogue:
                    diagnoses = response.get("diagnoses")
                    diagnoses_mapped = all_mapped(diagnoses, self.diagnosis_catalogue)
                    if candidate["items"] and (not isinstance(diagnoses, list) or not diagnoses):
                        raise WorkflowFailure("physician did not supply a structured diagnosis")
                    if candidate["items"] and not diagnoses_mapped:
                        raise WorkflowFailure("physician diagnosis is not mapped in the hospital catalogue")
                if diagnoses_mapped:
                    self.perform("consultation.save", {"artifact_id": self.prefix + ":consultation",
                                 "content": response, "transcript": self.physician_transcript()}, "doctor")
                else:
                    # Native diagnosis persistence requires a mapped diagnosis.
                    # An honest no-Rx/undetermined diagnosis remains an audited
                    # clinical decision; never invent a code to satisfy the HIS.
                    self.event("consultation_recorded_without_native_diagnosis", content=deepcopy(response),
                        content_hash=digest(response), persistence="private_local_audit_journal",
                        native_write_attempted=False, reason="no_prescription_and_no_mapped_current_diagnosis")
                    self.result["artifacts"]["consultation_persistence"] = {
                        "clinical_decision_recorded": True, "native_diagnosis_recorded": False,
                        "persistence": "private_local_audit_journal" if self.directory else "in_memory_engineering_test"}
                self.event("consultation_completed", content_hash=digest(response),
                           physician_dialogue_segments=len(self.physician_transcript()))
                eligibility = {"status": "prescription_observed" if candidate["items"] else
                               "not_applicable_to_observed_decision",
                    "decision": "prescription_issued" if candidate["items"] else "no_prescription_issued",
                    "source": "actual_physician_consultation", "source_response_hash": digest(response),
                    "clinical_appropriateness": "not_assessed_outside_programmatic_scope"}
                if not candidate["items"]:
                    if self.prescribing_required:
                        explicit_none = response.get('ed_prescription_reassessment', {}).get('order_actions') == []
                        eligibility.update(status='verified_no_action_at_checkpoint' if explicit_none else 'pending_with_treating_physician',
                                           decision='no_order_action' if explicit_none else 'prescribing_pending')
                    eligibility["stated_reason"] = (response.get("no_prescription_reason") or
                        candidate.get("no_prescription_reason") or response.get("plan"))
                    eligibility["three_task_chain_complete"] = False
                    self.event("prescription_not_issued", disposition=eligibility['decision'],
                               clinical_appropriateness="not_assessed_outside_programmatic_scope")
                self.result["artifacts"]["prescription_eligibility"] = eligibility
                return response
            if response.get("action") != "ask" or (not self.continuous and turn >= self.runner.limits["consultation_turns"]):
                raise WorkflowFailure("consultation did not finish within the declared limit")
            self.activity("doctor", "diagnostic")
            question = response['question']
            key = ' '.join(question.casefold().split())
            evidence = digest([self.patient_memory, self.history['queried_pages']]) if self.post_signature_review else None
            if self.post_signature_review and unanswered.get(key) == evidence:
                self.event('ed_intake_source_exhausted', question_hash=digest(key), physician_call=self.calls[-1]['sequence'])
                require_assessment = True
                continue
            answer = self.ask_patient('doctor', question, 'consultation')
            # A partial reply leaves an unanswered part even when it discloses known facts.
            if self.post_signature_review and answer['unanswered']:
                unanswered[key] = evidence
            turn += 1
        raise AssertionError("unreachable consultation")

    def ed_available_rows(self, section):
        rows = self.case['his_initial'].get(section, [])
        if (section in {'ed_reassessment_reports','ed_reassessment_workup'} and self.ed_prescribing_phase == 'reassessment'
                and self.ed_checkpoints):
            cutoff = self.ed_checkpoints[self.ed_checkpoint_index]['release_before_seconds']
            return [row for row in rows if reported_before(row, cutoff)]
        return rows

    def ed_chart_rows(self, section, *, release_phase=None):
        if (self.prescribing_required and section in {'ed_closing_reports', 'ed_closing_workup'}
                and self.ed_prescribing_phase != 'closed'):
            raise WorkflowFailure('Closing ED records require a verified prescription signature')
        if (self.prescribing_required and section in {'ed_reassessment_reports','ed_reassessment_workup'}
                and self.ed_prescribing_phase == 'presentation'):
            raise WorkflowFailure('Reassessment requires the signed initial ED order')
        if release_phase is None and section in self.ed_report_rows:
            return self.ed_report_rows[section]
        rows, offset = [], 0
        while True:
            request = {'section': section, 'offset': offset, 'limit': MAX_PAGE_RECORDS}
            if release_phase is not None:
                request['term'] = release_phase
            page = self.perform('history.query', request, 'doctor', write=False)['page']
            if (page.get('section') != section or page['requires_expansion']
                    or any(not row.get('record_ref') for row in page['records'])):
                if self.prescribing_required:
                    self.event('ed_report_inventory_mismatch', section=section, reason='incomplete_readback')
                raise WorkflowFailure('Incomplete ED chart readback: ' + section)
            if release_phase is not None and any(row['record']['available_at'] != release_phase
                                                for row in page['records']):
                raise WorkflowFailure('ED result outside the requested release phase')
            rows.extend(page['records'])
            cursor = page['next_offset']
            if cursor is None:
                if len(rows) != page['matching_count']:
                    if self.prescribing_required:
                        self.event('ed_report_inventory_mismatch', section=section, reason='pagination_count',
                                   expected_rows=page['matching_count'], received_rows=len(rows))
                    raise WorkflowFailure('ED chart readback count differs: ' + section)
                if self.prescribing_required and section in emergency.WORKUP_SECTIONS.values():
                    source = emergency.SOURCE_ED_ADMINISTRATION
                    expected = Counter(digest(row) for row in self.ed_available_rows(section) if row.get('kind') == source)
                    actual = Counter(digest(row['record']) for row in rows if row['record'].get('kind') == source)
                    if expected != actual:
                        self.event('ed_report_inventory_mismatch', section=section, reason='source_administration_readback',
                                   expected_rows=expected.total(), received_rows=actual.total())
                        raise WorkflowFailure('Released medication administrations differ from the imported chart: ' + section)
                if self.prescribing_required and section in {'ed_workup', 'ed_lab_reports'}:
                    wave = 'presentation' if section == 'ed_workup' else (release_phase or '').removeprefix('ed_')
                    cutoff = self.ed_decision_hours(wave)
                    if cutoff is not None and any(
                            (when := row['record'].get('time', {}).get('recorded_offset_hours')) is not None
                            and when > cutoff and emergency.documented_allergy(row, wave) is not None for row in rows):
                        self.event('ed_report_inventory_mismatch', section=section, reason='allergy_record_after_stage_cutoff')
                        raise WorkflowFailure('ED allergy record was assigned before its recorded availability: ' + section)
                if self.prescribing_required and release_phase is None and section in emergency.REPORT_SECTIONS.values():
                    material = self.ed_available_rows(section)
                    wave = next(w for w,s in emergency.REPORT_SECTIONS.items() if s == section)
                    cutoff = self.ed_decision_hours(wave)
                    if cutoff is not None and any(
                            (when := row['record'].get('time', {}).get('recorded_offset_hours')) is not None and when > cutoff
                            for row in rows):
                        self.event('ed_report_inventory_mismatch', section=section, reason='report_after_stage_cutoff')
                        raise WorkflowFailure('ED report was assigned before its recorded availability: ' + section)
                    def signature(row):
                        fields = ('source_ref', 'name', 'fluid', 'value_raw', 'numeric_value_raw',
                                  'unit_raw', 'flag_raw', 'value_source_column', 'lab_comment_raw',
                                  'available_at', 'time', 'allergy_update')
                        return digest([row.get(key) for key in fields])
                    if (len({r['record_ref'] for r in rows}) != len(rows)
                            or Counter(map(signature, material)) != Counter(signature(r['record']) for r in rows)):
                        self.event('ed_report_inventory_mismatch', section=section,
                                   expected_rows=len(material), received_rows=len(rows))
                        raise WorkflowFailure('Released ED report inventory differs from the imported chart: ' + section)
                    rows = [row for row in rows if emergency.reported_value(row['record'])
                            or row['record'].get('lab_comment_raw')]
                    self.ed_report_rows[section] = rows
                return rows
            if cursor <= offset:
                raise WorkflowFailure('ED chart cursor did not advance')
            offset = cursor

    def open_ed_diagnostic_directory(self, stage='presentation'):
        def names(section):
            if self.ips_on_demand:
                return list(dict.fromkeys(str(row['name']) for row in self.ed_available_rows(section)
                                          if row.get('name')))
            if not self.prescribing_required:
                return sorted({str(row[field]) for row in self.case['his_initial'].get(section, [])
                               for field in ('name', 'fluid') if row.get(field)})
            return sorted({row['record']['name'] for row in self.ed_chart_rows(section) if row['record'].get('name')})
        sections = {}
        for wave, section in emergency.REPORT_SECTIONS.items():
            if section in self.case['his_initial']:
                sections[section] = names(section)
            if wave == stage:
                break
        initial = sections.get('ed_diagnostic_reports', [])
        later = sections.get('ed_reassessment_reports', [])
        self.history['ed_diagnostic_directory'] = {
            'stage': stage, 'released_sections': list(sections), 'tests_by_section': sections,
            'section': 'ed_diagnostic_reports', 'reassessment_section': 'ed_reassessment_reports',
            'initial_tests': initial, 'reassessment_tests': later,
            'available_tests': sorted({title for titles in sections.values() for title in titles}),
            'access': ('Search by test name to retrieve the relevant released value. '
                       'Use ed_workup or ed_reassessment_workup for other released facts.'
                       if self.ips_on_demand else
                       'These tests have released values, report text, or an attributed laboratory comment. '
                       'A comment alone does not establish a measured value. All rows are included in chart review. '
                       'Query the displayed name and section to revisit a result.' if self.prescribing_required else
                       'Only results available at this review point are listed. Query a released section by test name.')}
        self.result['artifacts']['visible_history'] = deepcopy(self.history)
        self.event('ed_diagnostic_directory_opened', stage=stage, initial=len(initial), reassessment=len(later))

    def request_ed_source_inventory(self, wave, available, unread, *, source_refs):
        self.respond('doctor', {'action': 'request_ed_source_inventory', 'stage_of_visit': wave},
                     phase='ed_source_inventory_' + wave)
        inventory = {'stage': wave, 'available': available, 'to_review': unread}
        self.event('ed_source_inventory_requested', inventory=deepcopy(inventory),
                   sources=source_refs, physician_call=self.calls[-1]['sequence'])
        return inventory

    def ed_quote_origin(self, quote):
        if quote is None:
            return None
        current = self.calls[-1]
        source = emergency.review_quote_source(quote, current['observation'], self.calls[:-1])
        if source is None:
            raise WorkflowFailure('The reading receipt has no identifiable delivered source.')
        return source or current['sequence']

    def review_ed_chart(self, wave, sections):
        available = self.history['initial_view']['sections']
        material = []
        if wave in ('reassessment', 'closing') and emergency.WORKUP_SECTIONS[wave] not in sections:
            sections = (*sections, emergency.WORKUP_SECTIONS[wave])
        for section in sections:
            if section in INDEX_ED_SECTIONS:
                if section not in self.case['his_initial']:
                    continue
            elif not available.get(section, {}).get('total_count'):
                continue
            rows = self.ed_chart_rows(section)
            if rows:
                material.append((section, rows))
        reviewed = []
        panels = []
        delivered = Counter()
        counts = {section:len(rows) for section, rows in material}
        sources = {section: [row['record_ref'] for row in rows] for section, rows in material}
        if wave == 'reassessment':
            earlier = self.ed_review.get(wave, {})
            reviewed.extend(earlier.get('physician_findings', []))
            panels.extend(earlier.get('results', []))
            material = [(s, [r for r in rows if (s, r['record_ref']) not in self.ed_reviewed_refs]) for s,rows in material]
        inventory = None
        if self.ed_source_review_required:
            inventory = self.request_ed_source_inventory(
                wave, counts, {section: len(rows) for section, rows in material}, source_refs=sources)
        for number, (tables, receipts) in enumerate(emergency.chart_review_pages(material), 1):
            self.activity('doctor', 'history_lookup')
            observation = {
                'action': 'review_ed_chart_page', 'stage_of_visit': wave, 'page_number': number,
                'time_basis': 'Hours relative to this ED arrival. Negative times belong to prior history. '
                              'Use specimen and reporting times as recorded. A prior course does not establish current use.',
                'presenting_history': self.physician_transcript(), 'tables': tables}
            if inventory is not None:
                observation['source_quote_required'] = True
                observation.pop('presenting_history')
                previous = next((c for c in reversed(self.calls) if c['role'] == 'doctor' and c['status'] == 'completed'
                                 and c['observation'].get('source_quote_required')), None)
                if previous is not None:
                    observation['previous_reading_receipt'] = {'physician_call': previous['sequence'],
                                                               'evidence_quote': previous['response']['evidence_quote']}
                if number == 1:
                    observation['source_inventory'] = inventory
                self.event('ed_chart_page_prepared', stage=wave, page_number=number,
                           sources=receipts, content_hash=digest(tables), first_call=len(self.calls) + 1)
            if self.longitudinal_allergy and any(table['section'] == 'allergy_record' for table in tables):
                observation['required_evidence_section'] = 'allergy_record'
            reply = self.respond('doctor', observation, phase='ed_chart_review_' + wave)
            reviewed.append(reply['findings'])
            if self.prescribing_required:
                delivered.update((part['section'], ref) for part in receipts for ref in part['refs'])
            if wave != 'prior':
                panels.extend(tables)
            self.event('ed_chart_page_reviewed', stage=wave, page_number=number, sources=receipts,
                       content_hash=digest(tables), physician_call=self.calls[-1]['sequence'],
                       evidence_quote=reply.get('evidence_quote'),
                       evidence_source_call=self.ed_quote_origin(reply.get('evidence_quote')))
        if self.prescribing_required:
            expected = Counter((section, r['record_ref']) for section, rows in material for r in rows)
            if expected != delivered:
                self.event('ed_report_inventory_mismatch', stage=wave, reason='physician_page_receipts')
                raise WorkflowFailure('Hospital chart and physician page receipts differ: ' + wave)
        if wave == 'reassessment':
            self.ed_reviewed_refs.update(delivered)
        if self.case['data_kind'] == 'mimic_derived':
            self.patient_memory = with_medication_memory(self.case['case_id'], self.patient_memory, self.case['his_initial'],
                released_workup=(row['record'] for section, rows in material
                                 if section in emergency.WORKUP_SECTIONS.values() for row in rows))
        for section, rows in material:
            if section == 'ed_workup' or section in emergency.REPORT_SECTIONS.values():
                self.record_ed_allergy_updates(rows, wave)
        self.ed_review[wave] = {'reviewed_counts': counts, 'physician_findings': reviewed}
        if inventory is not None:
            self.ed_review[wave]['source_inventory'] = inventory
        if wave == 'prior' and self.prescribing_required:
            medications = emergency.reviewed_prior_medications(material)
            if medications:
                self.ed_review[wave]['prior_medications'] = medications
        if panels:
            self.ed_review[wave]['results'] = panels
        if wave == 'reassessment':
            self.ed_review[wave]['timing'] = (
                'Later source observations. Interpret the initial presentation at its own time. '
                'A later value alone does not establish a treatment response or an untreated course in this simulation.')
        self.result['artifacts']['ed_chart_review'] = deepcopy(self.ed_review)

