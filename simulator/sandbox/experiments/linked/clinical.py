        if key in self.history:
            return False
        visible = self.ed_chart_rows('ed_lab_reports', release_phase=phase)
        self.record_ed_allergy_updates(visible, phase)
        view = emergency.lab_report_view(visible, phase)
        self.history[key] = {'time_unit': 'hours since ED arrival', 'panels': view,
                             'available_through_hour': max((p['report_hour'] for p in view), default=None)}
